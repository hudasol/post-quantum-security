#!/usr/bin/env python3
"""Summarise the emulated sweep in qemu_results/ (label: emulated).

Writes qemu_results/ANALYSIS.md: correctness, stack by core and optimisation level, Cortex-M33 versus
Cortex-M4, the current toolchain versus the first round results of 2026-10-12 (read from git history,
commit 1060a1d, built with arm-none-eabi-gcc 13.2.1 and QEMU 8.2.2), ordering by parameter set, and the
effect of -Os and -O3. Emulator figures are never cycles or times. Run from bench/mcu/ or anywhere."""
import csv
import io
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "qemu_results")
FIRST_ROUND = "1060a1d"
ORDER = {"ML-KEM": ["ML-KEM-512", "ML-KEM-768", "ML-KEM-1024"],
         "ML-DSA": ["ML-DSA-44", "ML-DSA-65", "ML-DSA-87"]}
OPS = {"ML-KEM": ["keygen", "encaps", "decaps"], "ML-DSA": ["keygen", "sign", "verify"]}
PNAME = {("mlkem", s): f"ML-KEM-{s}" for s in ("512", "768", "1024")}
PNAME.update({("mldsa", s): f"ML-DSA-{s}" for s in ("44", "65", "87")})


def read(name):
    with open(os.path.join(RES, name), newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def first_round(name):
    try:
        txt = subprocess.run(["git", "show", f"{FIRST_ROUND}:bench/mcu/qemu_results/{name}"], cwd=HERE,
                             capture_output=True, text=True, check=True).stdout
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None
    return list(csv.DictReader(io.StringIO(txt)))


def pct(a, b):
    return 100.0 * (a / b - 1.0)


def main():
    checks, stack, size = read("checks.csv"), read("stack.csv"), read("image_size.csv")
    cfg = {r["key"]: r["value"] for r in read("config.csv")}
    st = {(r["board"], r["opt"], r["param"], r["op"]): int(r["stack_bytes"]) for r in stack}
    tx = {(r["board"], r["opt"], PNAME[(r["alg"], r["param"])]): int(r["text_bytes"]) for r in size}
    L = ["# Emulated sweep: analysis", "",
         "Author: Huda Mueen. Generated by `bench/mcu/analyze_qemu.py` (called at the end of `run_qemu.sh`). "
         "Label: **emulated**. Stack is a high water mark by stack painting; size is from arm-none-eabi-size. "
         f"No figure here is a cycle count or a time. Toolchain: {cfg.get('compiler', '?')}; {cfg.get('qemu', '?')}. "
         "What QEMU cannot show is in `LIMITS.md`.", ""]
    fails = [r for r in checks if r["fail"] != "0"]
    L += ["## Correctness", "",
          f"{len(checks)} builds checked, {len(checks) - len(fails)} passed every check "
          f"(ML-KEM round trips; ML-DSA sign, verify and rejection of a corrupted signature).", ""]
    L += ["## Stack high water mark (bytes) at -O2", "",
          "| parameter set | operation | Cortex-M4 (an386) | Cortex-M33 (an505) | M33 vs M4 |", "|---|---|---|---|---|"]
    worst = 0.0
    for alg, sets in ORDER.items():
        for ps in sets:
            for op in OPS[alg]:
                a, b = st[("an386", "-O2", ps, op)], st[("an505", "-O2", ps, op)]
                worst = max(worst, abs(pct(b, a)))
                L.append(f"| {ps} | {op} | {a:,} | {b:,} | {pct(b, a):+.1f}% |")
    L += ["", f"Largest M33 versus M4 difference over all operations at -O2: {worst:.1f}%.", ""]
    worst_all = max(abs(pct(st[("an505", o, ps, op)], st[("an386", o, ps, op)]))
                    for o in ("-O2", "-Os", "-O3") for alg in ORDER for ps in ORDER[alg] for op in OPS[alg])
    L += [f"Over all three optimisation levels: {worst_all:.1f}%.", ""]
    fr_stack, fr_size = first_round("stack.csv"), first_round("image_size.csv")
    if fr_stack and fr_size:
        L += ["## Current toolchain versus the first round (Cortex-M4, -O2)", "",
              f"First round: commit {FIRST_ROUND}, arm-none-eabi-gcc 13.2.1, QEMU 8.2.2 "
              "(`docs/EMULATOR_RESULTS.md`).", "",
              "| parameter set | item | first round | now | change |", "|---|---|---|---|---|"]
        w = 0.0
        for r in fr_stack:
            now = st[("an386", "-O2", r["param"], r["op"])]
            w = max(w, abs(pct(now, int(r["stack_bytes"]))))
            L.append(f"| {r['param']} | stack {r['op']} | {int(r['stack_bytes']):,} | {now:,} | "
                     f"{pct(now, int(r['stack_bytes'])):+.1f}% |")
        for r in fr_size:
            ps = PNAME[(r["alg"], r["param"])]
            now = tx[("an386", "-O2", ps)]
            w = max(w, abs(pct(now, int(r["text_bytes"]))))
            L.append(f"| {ps} | text | {int(r['text_bytes']):,} | {now:,} | {pct(now, int(r['text_bytes'])):+.1f}% |")
        L += ["", f"Largest change: {w:.1f}%.", ""]
    L += ["## Ordering by parameter set", ""]
    bad = []
    for b in ("an386", "an505"):
        for o in ("-O2", "-Os", "-O3"):
            for alg, sets in ORDER.items():
                for op in OPS[alg]:
                    v = [st[(b, o, ps, op)] for ps in sets]
                    if not (v[0] < v[1] < v[2]):
                        bad.append(f"{b} {o} {alg} {op}: {v}")
    L += [("Stack grows strictly with the parameter set for every operation, core and optimisation level."
           if not bad else "Exceptions to strictly growing stack: " + "; ".join(bad) + "."), ""]
    L += ["## Optimisation level (text bytes; stack change versus -O2)", "",
          "| core | parameter set | text -O2 | text -Os | text -O3 | largest stack change -Os | largest stack change -O3 |",
          "|---|---|---|---|---|---|---|"]
    smaller, maxst = 0, 0.0
    for b in ("an386", "an505"):
        for alg, sets in ORDER.items():
            for ps in sets:
                t2, ts, t3 = tx[(b, "-O2", ps)], tx[(b, "-Os", ps)], tx[(b, "-O3", ps)]
                smaller += ts < t2
                cs = max((pct(st[(b, "-Os", ps, op)], st[(b, "-O2", ps, op)]) for op in OPS[alg]), key=abs)
                c3 = max((pct(st[(b, "-O3", ps, op)], st[(b, "-O2", ps, op)]) for op in OPS[alg]), key=abs)
                maxst = max(maxst, abs(cs), abs(c3))
                L.append(f"| {b} | {ps} | {t2:,} | {ts:,} | {t3:,} | {cs:+.1f}% | {c3:+.1f}% |")
    L += ["", f"-Os gives smaller text than -O2 for {smaller} of 12 images. Largest stack change against -O2: "
          f"{maxst:.1f}%.", "",
          "Text includes the harness and the C library; no baseline is subtracted.", ""]
    with open(os.path.join(RES, "ANALYSIS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L))
    print(f"checks {len(checks) - len(fails)}/{len(checks)}; M33 vs M4 worst {worst_all:.1f}%; "
          f"ordering exceptions {len(bad)}; -Os smaller {smaller}/12; stack change by opt {maxst:.1f}%")


if __name__ == "__main__":
    main()
