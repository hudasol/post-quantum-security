#!/usr/bin/env bash
# Second emulator (free): build a subset of the benchmark images for the STM32F4 Discovery (Cortex-M4F) and run
# them in Renode's stm32f4_discovery-kit platform. Label: EMULATED. Correctness checks and stack high water
# marks only; Renode does not model cycle accurate timing, caches or flash wait states, so BENCH rows are
# discarded. Compares stack with the QEMU mps2-an386 results at -O2 (different board files, same harness,
# library and compiler flags). Needs: RENODE=<path to renode>, arm-none-eabi-gcc, ./fetch_libs.sh already run.
set -euo pipefail
cd "$(dirname "$0")"
RENODE=${RENODE:-renode}
OUT=renode_results; rm -rf "$OUT"; mkdir -p "$OUT" build/arm
ITERS=${ITERS:-3}; SPAN=${SPAN:-65536}; WAIT=${WAIT:-120}
WORK=${WORK:-$HOME/renode-work}   # Renode cannot parse paths with spaces, so stage files here
mkdir -p "$WORK"
{
  echo "key,value"
  echo "label,emulated"
  echo "date_utc,$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "renode,$("$RENODE" --version 2>&1 | head -1 | tr ',' ' ')"
  echo "platform,platforms/boards/stm32f4_discovery-kit.repl (Cortex-M4F)"
  echo "compiler,$(arm-none-eabi-gcc --version | head -1 | tr ',' ' ')"
  echo "flags,-O2 -mcpu=cortex-m4 -mfpu=fpv4-sp-d16 -mfloat-abi=hard (bench/mcu/Makefile arm target)"
  echo "iterations_per_operation,$ITERS"
  echo "stack_paint_span_bytes,$SPAN"
  echo "ram_limit,128 KB contiguous SRAM as on the STM32F407 (board/renode_stm32f4/link.ld)"
} > "$OUT/config.csv"
echo "alg,param,check,ok,fail" > "$OUT/checks.csv"
echo "alg,param,op,stack_bytes" > "$OUT/stack.csv"
for cfg in mlkem:512 mlkem:768 mlkem:1024 mldsa:44; do
  alg=${cfg%%:*}; set=${cfg##*:}
  make -s arm CPU=cortex-m4 FPU=fpv4-sp-d16 ALG=$alg SET=$set ITERS=$ITERS STACK_SPAN=$SPAN ARM_OPT=-O2 \
       LDSCRIPT=board/renode_stm32f4/link.ld STARTUP=board/renode_stm32f4/startup.c >/dev/null 2>&1 \
    || { echo "BUILD FAILED $cfg"; exit 1; }
  cp "build/arm/${alg}_${set}.elf" "$WORK/image.elf"
  elf=$WORK/image.elf
  log=$WORK/renode_${alg}_${set}.log
  rm -f "$log"
  cat > "$WORK/run.resc" <<RESC
mach create
machine LoadPlatformDescription @platforms/boards/stm32f4_discovery-kit.repl
sysbus LoadELF @$elf
sysbus.usart2 CreateFileBackend @$log true
start
RESC
  # keep the monitor's input open for the run; at end of input Renode would stop the machine
  ( sleep "$WAIT" | "$RENODE" --disable-gui --console -e "include @$WORK/run.resc" > "$WORK/console.txt" 2>&1 & echo $! > "$WORK/renode.pid" )
  for i in $(seq 1 "$WAIT"); do
    if [ -f "$log" ] && grep -q '^CHECK' "$log"; then break; fi
    sleep 1
  done
  pkill -f "run.resc" 2>/dev/null || true; pkill -f "sleep $WAIT" 2>/dev/null || true; sleep 1
  grep -q '^CHECK' "$log" 2>/dev/null || { echo "NO CHECK LINE $cfg"; tail -5 "$WORK/console.txt"; exit 1; }
  grep '^CHECK' "$log" | sed 's/^CHECK,//' | tr -d '\r' >> "$OUT/checks.csv"
  grep '^STACK' "$log" | sed 's/^STACK,//' | tr -d '\r' >> "$OUT/stack.csv"
  echo "done $cfg"
done
python3 - <<'PY'
import csv
q = {(r["param"], r["op"]): int(r["stack_bytes"]) for r in csv.DictReader(open("qemu_results/stack.csv"))
     if r["board"] == "an386" and r["opt"] == "-O2"}
rows = list(csv.DictReader(open("renode_results/stack.csv")))
chk = list(csv.DictReader(open("renode_results/checks.csv")))
L = ["# Renode cross check (label: emulated)", "",
     "Author: Huda Mueen. Generated by `bench/mcu/run_renode.sh`. Same harness, library commits and compiler "
     "flags as the QEMU run, but different board files (STM32F4 Discovery in Renode versus MPS2 AN386 in QEMU). "
     "Correctness and stack only; no cycles or times. Configuration: `config.csv`.", "",
     f"Checks: {sum(r['fail'] == '0' for r in chk)} of {len(chk)} builds pass every check.", "",
     "| parameter set | operation | stack, Renode | stack, QEMU an386 -O2 | difference |", "|---|---|---|---|---|"]
for r in rows:
    a, b = int(r["stack_bytes"]), q[(r["param"], r["op"])]
    L.append(f"| {r['param']} | {r['op']} | {a:,} | {b:,} | {a - b:+,} B |")
open("renode_results/COMPARISON.md", "w", newline="\n").write("\n".join(L) + "\n")
print("\n".join(L[-len(rows):]))
PY
