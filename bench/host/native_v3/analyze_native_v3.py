#!/usr/bin/env python3
"""Analyse the third round host runs in raw/ (label: HOST MEASURED).

Per run and operation: median of the iterations left after dropping the first DROP. Across runs: median of
the run medians, median absolute deviation (MAD) of the run medians, and the spread (max minus min) over the
median. Ratios to ML-KEM-768 encaps are computed within each run (the order of runs was interleaved, so a run
of one binary is close in time to runs of the others) and summarised by their median and MAD. Ranks are
compared with the published pqm4 'clean' cycle counts in data/evidence.csv. Writes summary.csv and RESULTS.md."""
import csv
import glob
import os
import re
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
DROP = 20
OPS = [("ML-KEM", p, o) for p in ("ML-KEM-512", "ML-KEM-768", "ML-KEM-1024") for o in ("keygen", "encaps", "decaps")]
OPS += [("ML-DSA", p, o) for p in ("ML-DSA-44", "ML-DSA-65", "ML-DSA-87") for o in ("keygen", "sign", "verify")]
REF = ("ML-KEM", "ML-KEM-768", "encaps")


def mad(xs):
    m = statistics.median(xs)
    return statistics.median(abs(x - m) for x in xs)


def load_runs():
    per = {}
    for path in sorted(glob.glob(os.path.join(HERE, "raw", "run*_bench_*.csv"))):
        run = int(re.search(r"run(\d+)_", os.path.basename(path)).group(1))
        vals = {}
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                f = line.strip().split(",")
                if f[0] == "BENCH" and f[7] == "ns_host":
                    vals.setdefault((f[1], f[2], f[3]), []).append((int(f[5]), int(f[6])))
                if f[0] == "CHECK" and f[5] != "0":
                    raise SystemExit(f"{path}: failed check {line.strip()}")
        for k, v in vals.items():
            per.setdefault(k, {})[run] = statistics.median([x for i, x in sorted(v) if i >= DROP])
    return per


def pqm4_clean():
    out = {}
    with open(os.path.join(ROOT, "data", "evidence.csv"), newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            if "mupq/pqm4" in r["source_url"] and "implementation 'clean" in r["library"] and r["cycles"]:
                out[(r["scheme_family"], r["parameter_set"], r["operation"])] = (int(r["cycles"]), r["id"])
    return out


def spearman(a, b):
    rk = lambda v: [sorted(v).index(x) + 1 for x in v]  # noqa: E731
    ra, rb, n = rk(a), rk(b), len(a)
    return 1 - 6 * sum((x - y) ** 2 for x, y in zip(ra, rb)) / (n * (n * n - 1))


def main():
    per = load_runs()
    pq = pqm4_clean()
    rows = []
    for k in OPS:
        runs = sorted(per[k])
        meds = [per[k][r] for r in runs]
        m = statistics.median(meds)
        ratios = [per[k][r] / per[REF][r] for r in runs if r in per[REF]]
        rows.append({"alg": k[0], "param": k[1], "op": k[2], "runs": len(meds), "median_ns": m,
                     "mad_ns": mad(meds), "rel_mad": mad(meds) / m, "spread": (max(meds) - min(meds)) / m,
                     "ratio_median": statistics.median(ratios), "ratio_rel_mad": mad(ratios) / statistics.median(ratios),
                     "pqm4_clean_cycles": pq[k][0], "pqm4_row": pq[k][1]})
    ref = [r for r in rows if (r["alg"], r["param"], r["op"]) == REF][0]
    for r in rows:
        r["pqm4_ratio"] = r["pqm4_clean_cycles"] / ref["pqm4_clean_cycles"]
        r["ratio_diff"] = r["ratio_median"] / r["pqm4_ratio"] - 1.0
    rho = spearman([r["median_ns"] for r in rows], [r["pqm4_clean_cycles"] for r in rows])
    fields = ["alg", "param", "op", "runs", "median_ns", "mad_ns", "rel_mad", "spread", "ratio_median",
              "ratio_rel_mad", "pqm4_clean_cycles", "pqm4_row", "pqm4_ratio", "ratio_diff"]
    with open(os.path.join(HERE, "summary.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: ("%.6g" % r[k] if isinstance(r[k], float) else r[k]) for k in fields})
    with open(os.path.join(HERE, "config.csv"), newline="", encoding="utf-8") as fh:
        cfg = {r["key"]: r["value"] for r in csv.DictReader(fh)}
    with open(os.path.join(HERE, "state.csv"), newline="", encoding="utf-8") as fh:
        st = list(csv.DictReader(fh))
    mhz = [float(s["cpu_mhz"]) for s in st if s["cpu_mhz"]]
    load = [float(s["loadavg_1min"]) for s in st]
    sign = {r["param"]: r["median_ns"] for r in rows if r["op"] == "sign"}
    order_ok = sign["ML-DSA-44"] < sign["ML-DSA-65"] < sign["ML-DSA-87"]
    L = ["# Host measured baseline, third round", "",
         "Author: Huda Mueen. Generated by `bench/host/native_v3/analyze_native_v3.py` (called by "
         "`run_native_v3.sh`). Label: **host measured**. Nanoseconds on a PC; not microcontroller results and not "
         "transferable to one. Used only for ratios between algorithms and for rank order.", "",
         "## Method", "",
         f"CPU: {cfg.get('cpu_model')}; {cfg.get('environment')}; {cfg.get('compiler')}; flags {cfg.get('flags')}. "
         f"{cfg.get('runs_per_binary')} runs per binary, interleaved in an order shuffled with seed "
         f"{cfg.get('order_seed')}, each pinned to CPU {cfg.get('pinned_cpu')}, "
         f"{cfg.get('iterations_per_operation_per_run')} iterations per operation; the first {DROP} iterations of "
         "every run are dropped; one discarded warm up pass first. Statistic: median per run, then median and median "
         "absolute deviation (MAD) of the run medians. Machine state before each run is in `state.csv`: load average "
         f"{min(load):.2f} to {max(load):.2f}; reported CPU MHz {min(mhz):.0f} to {max(mhz):.0f} (the value the "
         "virtual machine reports; it need not follow the real clock).", "",
         "## Result", "",
         "| parameter set | operation | median (ns) | MAD / median | spread (max minus min) / median | "
         "within run ratio to ML-KEM-768 encaps (median, MAD / median) | ratio, pqm4 clean (published) | difference |",
         "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append("| %s | %s | %s | %.1f%% | %.1f%% | %.2f (%.1f%%) | %.2f (%s) | %+.0f%% |" % (
            r["param"], r["op"], f"{r['median_ns']:,.0f}", 100 * r["rel_mad"], 100 * r["spread"], r["ratio_median"],
            100 * r["ratio_rel_mad"], r["pqm4_ratio"], r["pqm4_row"], 100 * r["ratio_diff"]))
    worst = max(rows, key=lambda r: r["spread"])
    L += ["", "Host ratios and published ratios sit in labelled columns; absolute host and published values never "
          "share a column.", "",
          f"Largest spread: {worst['param']} {worst['op']}, {100 * worst['spread']:.1f} percent. Largest MAD over "
          f"median: {100 * max(r['rel_mad'] for r in rows):.1f} percent.", "",
          f"ML-DSA signing order on the host: 44 {sign['ML-DSA-44']:,.0f} ns, 65 {sign['ML-DSA-65']:,.0f} ns, 87 "
          f"{sign['ML-DSA-87']:,.0f} ns ({'expected order' if order_ok else 'ORDER INVERTED'}).", "",
          f"Spearman rank correlation of the 18 host medians with the 18 published pqm4 clean cycle counts: {rho:.3f}.",
          "", "## Limits", "",
          "1. The host runs mlkem-native and mldsa-native; the published rows are PQClean reference code on a "
          "Cortex-M4. Rank agreement does not mean cost agreement.",
          "2. CPU frequency was not under control; interleaving spreads its effect over all algorithms but does not "
          "remove it.",
          "3. ML-DSA signing time depends on the message; pqm4 reports a mean, this table a median.", ""]
    with open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L))
    print(f"max spread {100 * worst['spread']:.1f}% ({worst['param']} {worst['op']}); max rel MAD "
          f"{100 * max(r['rel_mad'] for r in rows):.1f}%; sign order ok {order_ok}; spearman {rho:.3f}")


if __name__ == "__main__":
    main()
