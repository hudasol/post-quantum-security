#!/usr/bin/env python3
"""Analyse the native host timing runs in raw/ (label: HOST MEASURED).

Statistic: for every run and operation, the median of the iterations left after dropping the first DROP
(in process warm up). Across runs: the median of the run medians and the coefficient of variation of the run
medians. Ratios between operations are compared with the published pqm4 Cortex-M4 cycle counts of the
portable reference ('clean') implementation in data/evidence.csv. Host times are never presented as
microcontroller times; only ratios are compared, and the comparison itself shows how far ratios move.
Writes summary.csv and RESULTS.md next to this file."""
import csv
import glob
import os
import re
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
DROP = 20
OPS = [("ML-KEM", p, o) for p in ("ML-KEM-512", "ML-KEM-768", "ML-KEM-1024") for o in ("keygen", "encaps", "decaps")]
OPS += [("ML-DSA", p, o) for p in ("ML-DSA-44", "ML-DSA-65", "ML-DSA-87") for o in ("keygen", "sign", "verify")]
REF = ("ML-KEM", "ML-KEM-768", "encaps")


def load_runs():
    per = {}
    for path in sorted(glob.glob(os.path.join(HERE, "raw", "run*_bench_*.csv"))):
        run = int(re.search(r"run(\d+)_", os.path.basename(path)).group(1))
        vals = {}
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                f = line.strip().split(",")
                if f[0] == "BENCH" and f[7] == "ns_host":
                    vals.setdefault((f[1], f[2], f[3]), []).append((int(f[5]), int(f[6])))
                if f[0] == "CHECK" and f[5] != "0":
                    raise SystemExit(f"{path}: failed check {line.strip()}")
        for k, v in vals.items():
            kept = [x for i, x in sorted(v) if i >= DROP]
            per.setdefault(k, {})[run] = statistics.median(kept)
    return per


def pqm4_clean():
    out = {}
    with open(os.path.join(ROOT, "data", "evidence.csv"), newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            if "mupq/pqm4" in r["source_url"] and "implementation 'clean" in r["library"] and r["cycles"]:
                out[(r["scheme_family"], r["parameter_set"], r["operation"])] = (int(r["cycles"]), r["id"])
    return out


def ranks(xs):
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    r = [0.0] * len(xs)
    for pos, i in enumerate(order):
        r[i] = pos + 1.0
    return r


def spearman(a, b):
    ra, rb = ranks(a), ranks(b)
    n = len(a)
    return 1 - 6 * sum((x - y) ** 2 for x, y in zip(ra, rb)) / (n * (n * n - 1))


def main():
    per = load_runs()
    pq = pqm4_clean()
    rows = []
    for k in OPS:
        meds = [per[k][r] for r in sorted(per[k])]
        m = statistics.median(meds)
        cv = statistics.stdev(meds) / statistics.mean(meds) if len(meds) > 1 else 0.0
        rows.append({"alg": k[0], "param": k[1], "op": k[2], "runs": len(meds), "median_ns": m,
                     "cv_of_run_medians": cv, "pqm4_clean_cycles": pq[k][0], "pqm4_row": pq[k][1]})
    ref = [r for r in rows if (r["alg"], r["param"], r["op"]) == REF][0]
    for r in rows:
        r["host_ratio"] = r["median_ns"] / ref["median_ns"]
        r["pqm4_ratio"] = r["pqm4_clean_cycles"] / ref["pqm4_clean_cycles"]
        r["ratio_diff"] = r["host_ratio"] / r["pqm4_ratio"] - 1.0
    rho = spearman([r["median_ns"] for r in rows], [r["pqm4_clean_cycles"] for r in rows])
    fields = ["alg", "param", "op", "runs", "median_ns", "cv_of_run_medians", "host_ratio",
              "pqm4_clean_cycles", "pqm4_row", "pqm4_ratio", "ratio_diff"]
    with open(os.path.join(HERE, "summary.csv"), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: ("%.6g" % r[k] if isinstance(r[k], float) else r[k]) for k in fields})
    cfg = {}
    with open(os.path.join(HERE, "config.csv"), newline="", encoding="utf-8") as fh:
        cfg = {r["key"]: r["value"] for r in csv.DictReader(fh)}
    sign44 = [r for r in rows if r["param"] == "ML-DSA-44" and r["op"] == "sign"][0]
    worst = max(rows, key=lambda r: abs(r["ratio_diff"]))
    L = ["# Host measured baseline: mlkem-native and mldsa-native on the PC", "",
         "Author: Huda Mueen. Generated by `bench/host/native/analyze_native.py` (called by `run_native.sh`). "
         "Label: **host measured**. These are nanoseconds on a PC, not microcontroller results, and they do not "
         "transfer to a microcontroller. They are used only for ratios between algorithms.", "",
         "## Method", "",
         f"CPU: {cfg.get('cpu_model', '?')}; {cfg.get('kernel', '?')}; {cfg.get('compiler', '?')}; flags "
         f"{cfg.get('flags', '?')}. Same harness and library commits as the emulated runs (`config.csv`). One "
         f"discarded warm up run of every binary, then {cfg.get('runs', '?')} runs pinned to CPU "
         f"{cfg.get('pinned_cpu', '?')}, {cfg.get('iterations_per_operation_per_run', '?')} iterations per operation "
         f"per run; the first {DROP} iterations of every run are dropped as in process warm up. Statistic: median "
         "per run, then the median of the run medians; spread: coefficient of variation of the run medians. "
         "Frequency scaling and turbo were not controlled (no administrator rights), which is a stated limit.", "",
         "## Result", "",
         "| parameter set | operation | median (ns) | CV of run medians | ratio to ML-KEM-768 encaps, host | "
         "ratio, pqm4 clean Cortex-M4 (published) | host ratio vs published ratio |",
         "|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append("| %s | %s | %s | %.1f%% | %.2f | %.2f (%s) | %+.0f%% |" % (
            r["param"], r["op"], f"{r['median_ns']:,.0f}", 100 * r["cv_of_run_medians"], r["host_ratio"],
            r["pqm4_ratio"], r["pqm4_row"], 100 * r["ratio_diff"]))
    L += ["", "The ratio columns compare a host measured ratio with a ratio of published cycle counts; the "
          "absolute values (ns and cycles) are never set on one axis.", "",
          f"ML-DSA-44 sign over ML-KEM-768 encaps: host {sign44['host_ratio']:.1f}, published pqm4 clean "
          f"{sign44['pqm4_ratio']:.1f}.", "",
          f"Spearman rank correlation of the 18 host medians with the 18 published pqm4 clean cycle counts: "
          f"{rho:.3f}. Largest disagreement of a ratio: {worst['param']} {worst['op']} "
          f"({100 * worst['ratio_diff']:+.0f}%).", "",
          "## Post hoc check (not in the predictions): ratios within each run", "",
          "The run medians drift between runs (see the CV column), which points at CPU frequency changes "
          "inside the virtual machine. As a check added after seeing the data, the ratio to ML-KEM-768 encaps "
          "is also computed inside each run and then summarised across runs.", "",
          "| parameter set | operation | median of within run ratios | lowest | highest |", "|---|---|---|---|---|"]
    for r in rows:
        k = (r["alg"], r["param"], r["op"])
        rr = [per[k][run] / per[REF][run] for run in sorted(per[k]) if run in per[REF]]
        L.append("| %s | %s | %.2f | %.2f | %.2f |" % (r["param"], r["op"], statistics.median(rr), min(rr), max(rr)))
    L += ["", "A wide range here means even ratios from this host are unstable and should not be quoted alone.", "",
          "## Limits", "",
          "1. Different implementations: the host runs mlkem-native and mldsa-native (portable C), while the "
          "published pqm4 'clean' rows are PQClean reference code on a Cortex-M4; agreement of ranks does not "
          "mean agreement of cost.",
          "2. A PC has caches, out of order execution and a 64 bit datapath; a Cortex-M4 has none of these, so "
          "ratios shift. That shift is why these numbers are not transferable.",
          "3. ML-DSA signing time depends on the message (rejection sampling); the harness signs a different "
          "message each iteration, and pqm4 reports a mean, not a median.",
          "4. CPU frequency was not fixed.", ""]
    with open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L))
    print(f"ops {len(rows)}; max CV {100 * max(r['cv_of_run_medians'] for r in rows):.2f}%; "
          f"sign44/encaps768 host {sign44['host_ratio']:.2f}; spearman {rho:.3f}; "
          f"worst ratio diff {worst['param']} {worst['op']} {100 * worst['ratio_diff']:+.1f}%")


if __name__ == "__main__":
    main()
