def load(platform, exp):
    p = os.path.join(K.OUT_DIR, platform, exp, "build_record.json")
    if not os.path.exists(p):
        return None
    with open(p) as fh:
        return json.load(fh)


def size_rows(records):
    rows = []
    for rec in records:
        for im in rec["images"]:
            rows.append({"label": "host measured", "experiment": im["experiment"],
                         "platform": im["platform"], "scheme": im["scheme"],
                         "variant": im["variant"], "kind": im["kind"],
                         "cache_pass": im.get("cache_pass", "on"),
                         "iterations": im["iterations"], "image": im["image"],
                         "text_bytes": im["text"], "data_bytes": im["data"],
                         "bss_bytes": im["bss"], "total_dec_bytes": im["dec"],
                         "toolchain": rec["toolchain"], "pqm4_commit": rec["pqm4_commit"]})
    return rows


def shorten(cmd, rec):
    s = " ".join(cmd)
    return s.replace(K.WORK, "$WORK").replace(os.path.dirname(os.path.dirname(HERE)), "$REPO")


def command_block(rec, limit=None):
    cmds = [c for c in rec["commands"] if c["cmd"][0] in ("make", "rm", "arm-none-eabi-gcc",
                                                          "arm-none-eabi-objcopy", "git")]
    out, seen = [], set()
    for c in cmds:
        s = shorten(c["cmd"], rec)
        if s in seen:
            continue
        seen.add(s)
        out.append(f"{s}    # rc={c['rc']}")
    if limit and len(out) > limit:
        out = out[:limit] + [f"... ({len(cmds) - limit} more in build_record.json)"]
    return out


def write(records, md_path, csv_path):
    rows = size_rows(records)
    with open(csv_path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=SIZE_COLUMNS)
        w.writeheader()
        w.writerows(rows)
