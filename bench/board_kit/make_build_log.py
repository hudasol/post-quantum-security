         f"{K.MLDSA_NATIVE[1]} `{K.MLDSA_NATIVE[2]}`.",
         "- Toolchain used here: " + "; ".join(f"`{t}`" for t in tool) + ". pqm4's README names "
         "Arm GNU Toolchain 11.3.Rel1 for its published results, so code generation may differ.",
