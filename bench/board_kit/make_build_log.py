#!/usr/bin/env python3
"""Write build_log.md and image_sizes.csv from the build records of build_b0.py and build_b1.py.

Author: Huda Mueen. Every number in both files comes from the JSON records (commands, return
codes, toolchain version line, arm-none-eabi-size output). Image sizes are measured on the host
with arm-none-eabi-size from images built here; label 'host measured'. They are whole image sizes
(scheme plus pqm4 platform layer, libopencm3 and C library), not pqm4's code size column, which
counts only the scheme's own code.
"""
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kit_config as K  # noqa: E402

