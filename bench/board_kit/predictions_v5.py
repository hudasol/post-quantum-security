#!/usr/bin/env python3
"""Register the round 5 board predictions: the caches off pass of NUCLEO-L4R5ZI and of
NUCLEO-L552ZE-Q (Cortex-M33), from the cycle model of cyclemodel/ exactly as round 4 used it.

Author: Huda Mueen. Label of every prediction: modelled. Inputs (no number is typed here):
  cyclemodel/results/board_predictions.csv  written by cyclemodel/analyse.py (round 4 model; the
      script regenerates the file byte for byte from cyclemodel/results/traces.csv);
  cyclemodel/results/split.csv              the training and test halves of the model;
  cyclemodel/results/error_summary.csv      test half errors behind the intervals.
Outputs: bench/board_kit/predictions_v5_board.csv (one row per board and operation) and
docs/PREDICTIONS_V5_BOARD.md with its SHA-256 in docs/PREDICTIONS_V5_BOARD.md.sha256.
docs/PREDICTIONS_V4_BOARD.md is not touched.
"""
import argparse
import csv
import datetime as dt
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
RES = os.path.join(REPO, "cyclemodel", "results")
OUT_CSV = os.path.join(HERE, "predictions_v5_board.csv")
OUT_MD = os.path.join(REPO, "docs", "PREDICTIONS_V5_BOARD.md")
OUT_SHA = OUT_MD + ".sha256"
BOARDS = [("L4", "NUCLEO-L4R5ZI (STM32L4R5, Cortex-M4)", "nucleo-l4r5zi"),
          ("M33", "NUCLEO-L552ZE-Q (STM32L552, Cortex-M33)", "nucleo-l552ze-q")]
COLUMNS = ["label", "id", "board", "platform", "cache_pass", "target", "parameter_set",
           "implementation", "operation", "statistic", "cycles_modelled",
           "interval_lo_modelled", "interval_hi_modelled", "interval_kind", "in_sample",
           "counts_toward_refutation", "extrapolation_flags", "model", "toolchain"]


def read(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def build_rows(bp, split):
    train = {(r["parameter_set"], r["implementation"]) for r in split if r["half"] == "train"}
    harness = [r for r in bp if r["target"] == "harness (bench/mcu)"]
    harness.sort(key=lambda r: (r["parameter_set"], r["operation"]))
    rows = []
    for tag, board, platform in BOARDS:
        for i, r in enumerate(harness, 1):
            ins = (r["parameter_set"], r["implementation"]) in train
            rows.append({"label": "modelled", "id": f"V5B-{tag}-{i:02d}", "board": board,
                         "platform": platform, "cache_pass": "off", "target": r["target"],
                         "parameter_set": r["parameter_set"], "implementation": r["implementation"],
                         "operation": r["operation"], "statistic": "mean over all board runs",
                         "cycles_modelled": r["cycles_modelled"],
                         "interval_lo_modelled": r["pi95_envelope_lo_modelled"],
                         "interval_hi_modelled": r["pi95_envelope_hi_modelled"],
                         "interval_kind": "envelope of the full and reduced fit 95 percent "
                                          "prediction intervals (as round 4 for harness rows)",
                         "in_sample": "yes" if ins else "no",
                         "counts_toward_refutation": "no" if ins else "yes",
                         "extrapolation_flags": r["extrapolation_flags"], "model": r["model"],
                         "toolchain": r["toolchain"]})
    return rows


def fmt(x):
    return f"{int(round(float(x))):,}"


def write_md(rows, err, path):
    n_board = len(rows) // len(BOARDS)
    third = n_board // 3
    four_fifths = (4 * n_board) // 5
    out_of_sample = sum(1 for r in rows if r["in_sample"] == "no")
    extrap = sum(1 for r in rows if r["extrapolation_flags"] not in ("", "none"))
    test = next(e for e in err if e["model"] == "fitted" and e["subset"] == "test, all")
    L = ["# Board predictions for the caches off pass, round 5", "",
         "Author: Huda Mueen. Generated by `bench/board_kit/predictions_v5.py` from "
         "`cyclemodel/results/board_predictions.csv` (label: modelled) before any board session "
         "and before any caches off image has run on a board. The SHA-256 of this file as "
         "committed is in `docs/PREDICTIONS_V5_BOARD.md.sha256`; the file is never edited after "
         "the hash is taken. `docs/PREDICTIONS_V4_BOARD.md` stays as registered and is scored "
         "under its own rules and notes.", "",
         "## What the model assumes", "",
         "The cycle model of `cyclemodel/` is used exactly as in round 4: the same traces, the "
         "same non negative least squares fit on the training half of the published pqm4 rows "
         "(seed 20261020), the same reduced fit, and the same intervals. Running "
         "`python3 cyclemodel/analyse.py` regenerates its input file byte for byte. Its "
         "conditions: a Cortex-M4 at zero flash wait states with no cache and no bus contention, "
         "and code built with arm-none-eabi-gcc 13.2.1. Test half error of the full fit: median "
         f"absolute {float(test['median_abs_pct']):.2f} percent over {test['n']} rows, worst "
         f"{float(test['worst_abs_pct']):.1f} percent (`cyclemodel/results/error_summary.csv`).", "",
         "Two further assumptions apply here and are not tested by the model itself:", "",
         "1. **Caches off pass.** The predictions describe the images built with "
         "`-DBENCH_CACHE_OFF` (`bench/board_kit/b1/b1_main.c`), which switch the instruction "
         "cache, data cache and prefetch off at zero wait states after the clock set up. The "
         "rows the model was fitted on were measured by pqm4 with caches and prefetch on "
         "(`docs/PREDICTIONS_V4_BOARD_NOTES.md` note 9), so a board mean below a prediction may "
         "come from that and not from the model.",
         "2. **Cortex-M33 board.** For NUCLEO-L552ZE-Q the Cortex-M4 per class costs are applied "
         "unchanged to the instruction mix traced from the Cortex-M4 build of the same source. "
         "This assumes that the Cortex-M33 has the same cost per instruction class and that its "
         "build (`-mcpu=cortex-m33`) executes the same mix. Neither is sourced; the M33 rows test "
         "whether the Cortex-M4 model transfers, not the model on its own core. The board runs "
         "at its 4 MHz reset clock with the flash latency read back (zero expected) and the "
         "instruction cache (ICACHE) off.", "",
         "## Which rows are in sample", "",
         f"All {len(rows)} rows predict the repository harness (mlkem-native and mldsa-native "
         "v2.0.0, -O2), which the model was never fitted on: "
         f"{out_of_sample} of {len(rows)} rows are out of sample "
         "(`cyclemodel/results/split.csv` holds only pqm4 binaries). "
         f"{extrap} of {len(rows)} rows carry extrapolation flags (the harness mix lies outside "
         "the training mix for at least one instruction class). The six in sample pqm4 m4f "
         "rows of round 4 (BP22 to BP24, BP28 to BP30) are B0 images, which run in the caches "
         "on pass only; they are not registered here.", "",
         "## Statistic and verdicts", "",
         "Each prediction is a mean over messages, so each verdict uses the board mean of all "
         "iterations of all power cycles of the caches off image; the median and spread are "
         "reported beside it, and the number of signing messages is stated because signing is "
         "skewed by rejection sampling. A row is a hit if the board mean lies inside its "
         "interval, a miss otherwise. Misses stay.", "",
         "## Refutation rules (out of sample rows only; applied per board)", "",
         f"1. The model is refuted for a board if more than a third of its {n_board} rows miss "
         f"(more than {third}).",
         f"2. It is also refuted for a board if more than four fifths of the signed errors "
         f"(board mean minus prediction) share one sign (more than {four_fifths} of {n_board}).",
         "3. A row counts only if its log shows `cache_pass,off`, `cache_off_applied,1` and "
         "`flash_ws,0` (parse.py turns each into a check). If no row of a board can be measured "
         "that way, the rules are not applied for that board and the session is reported as a "
         "check of conditions only.",
         "4. For NUCLEO-L552ZE-Q a refutation means that the Cortex-M4 model does not transfer to "
         "this Cortex-M33 board; it is reported separately and does not refute the model on the "
         "Cortex-M4 board.", ""]
    for tag, board, platform in BOARDS:
        L += [f"## {board}, caches off pass", "",
              "| ID | parameter set | implementation | operation | point prediction (cycles) | "
              "registered interval (cycles) | counts |", "|---|---|---|---|---|---|---|"]
        for r in rows:
            if r["platform"] != platform:
                continue
            L.append(f"| {r['id']} | {r['parameter_set']} | {r['implementation']} | "
                     f"{r['operation']} | {fmt(r['cycles_modelled'])} | "
                     f"{fmt(r['interval_lo_modelled'])} to {fmt(r['interval_hi_modelled'])} | "
                     f"{r['counts_toward_refutation']} |")
        L.append("")
    L += ["Rows: `bench/board_kit/predictions_v5_board.csv`. Scoring: `bench/board_kit/compare.py` "
          "keeps the cache passes apart and marks which rows meet the model's conditions.", ""]
    with open(path, "w") as fh:
        fh.write("\n".join(L))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--no-hash", action="store_true", help="do not write the .sha256 file")
    a = ap.parse_args(argv)
    rows = build_rows(read(os.path.join(RES, "board_predictions.csv")),
                      read(os.path.join(RES, "split.csv")))
    with open(OUT_CSV, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=COLUMNS)
        w.writeheader()
        w.writerows(rows)
    write_md(rows, read(os.path.join(RES, "error_summary.csv")), OUT_MD)
    digest = hashlib.sha256(open(OUT_MD, "rb").read()).hexdigest()
    if not a.no_hash:
        stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        with open(OUT_SHA, "w") as fh:
            fh.write(f"{digest}  docs/PREDICTIONS_V5_BOARD.md\n{stamp}\n")
    print(f"rows={len(rows)} sha256={digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
