"""Generate docs/SITL_STUDY.md from sitl/results/*.csv (every number in the text is read from those files)."""
import json
import os
import sys

import numpy as np
import pandas as pd

from mission import model
from . import config as cfgmod

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RES = os.path.join(HERE, 'results')


def f(x, nd=3):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return 'n/a'
    if isinstance(x, (int, np.integer)):
        return str(int(x))
    return f'{x:.{nd}f}'


def main():
    summ = pd.read_csv(os.path.join(RES, 'summary.csv'))
    comp = pd.read_csv(os.path.join(RES, 'comparison.csv'))
    runs = pd.read_csv(os.path.join(RES, 'runs.csv'))
    mis = pd.read_csv(os.path.join(RES, 'missions.csv'))
    s = cfgmod.load_settings()
    a = model.load_assumptions()
    with open(os.path.join(RES, 'environment.json')) as fh:
        env = json.load(fh)
    profiles = [p for p in cfgmod.PROFILES if p in set(summ.profile)]
    L = []
    w = L.append

    def val(p, k, metric, col='value'):
        r = summ[(summ.profile == p) & (summ.config == k) & (summ.metric == metric)]
        return r.iloc[0][col] if len(r) else np.nan

    w('# Software in the loop study of command authentication over an emulated link')
    w('')
    w('Author: Huda Mueen.')
    w('')
    w('Status: SITL measured (timings that include the flight stack, taken from a flight stack running in software in the '
      'loop on the host at a pinned version, with the link emulated) and emulated (quantities produced by the emulated link '
      'alone). No timing in this document is a timing on flight hardware, and no radio was used. Generated by '
      '`python3 -m sitl.make_doc` from `sitl/results/`.')
    w('')
    w('## 1. Question')
    w('')
    w('Do the availability and the added latency per command that the mission study (`docs/MISSION_STUDY.md`, label '
      'estimated) computes for its architectures hold when a real flight stack answers the commands? Four configurations '
      'are compared on the same flight stack, the same scripted missions and the same emulated link.')
    w('')
    w('## 2. Set up')
    w('')
    w(f'- Flight stack: {env["flight_stack"]}. PX4 was the first choice; {env["px4_note"]}')
    w(f'- Ground station: pymavlink {env["pymavlink"]} in Python {env["python"]}; host {env["host"]}.')
    w('- Mission: upload (takeoff to {0} m, a {1} m leg north, a {1} m leg east, land), mode AUTO, arm; from arming until '
      'the vehicle has landed and disarmed, the ground station sends one COMMAND_LONG (MAV_CMD_DO_SET_SERVO to an output with no function) every '
      '{2} s, the drone command rate of `mission/traffic.csv`. Latency is the time from the ground send to the '
      'COMMAND_ACK of the flight stack arriving back at the ground station.'.format(
          f(s['takeoff_alt_m'], 0), f(s['leg_m'], 0), f(1.0 / model.command_rate('drone'), 1)))
    w('- Link: a relay between the ground station (UDP) and SERIAL1 of the vehicle (TCP) parses MAVLink frames and '
      'sends them over one emulated half duplex channel with the rate, fragmentation and frame loss of the mission study '
      '(`linksim/params.csv`, `mission/assumptions.csv`); command, acknowledgement and handshake frames are retransmitted '
      'after the timeout of `linksim/params.csv`, telemetry frames are not. tc netem was not used (it needs root and '
      'network namespaces).')
    w(f'- Outages: one outage per mission, starting uniformly between {f(s["outage_window_start_s"], 0)} s and '
      f'{f(s["outage_window_end_s"], 0)} s after arming, with an exponential duration of mean '
      f'{f(a["outage_mean_s"], 0)} s (the mission study mean). One outage in a flight of about one minute is close to '
      'the 60 per hour point of the mission study outage sweep, which is the study value used for the comparison of '
      'availability with outages.')
    w('- Seeds: run i of a configuration and profile uses seed {0} plus 1000 times the profile index plus 100 times the '
      'configuration index plus i; every seed is stored in `sitl/results/missions.csv`.'.format(int(s['seed'])))
    w('')
    w('| configuration | what is on the link | vehicle side delay | mission study architecture used for comparison |')
    w('|---|---|---|---|')
    for k in cfgmod.CONFIGS:
        sc = cfgmod.security_config(k)
        what = {'none': 'MAVLink 2 frames as sent',
                'signing': 'MAVLink 2 frames with the 13 B signature field added by the flight stack and the ground station (real signing, key provisioned over the wired port with SETUP_SIGNING)',
                'hybrid': 'handshake of {0} B in four flights (design change F1, the vehicle signs too) before each mission, then {1} B added to every frame by the relay pair; teardown after {2} s without frames and a new handshake'.format(
                    sum(x[1] for x in sc['flights']), sc['tag_bytes'], f(sc.get('timeout_s', np.nan), 0)),
                'pqsig': '{0} B added to every command, sent in file transfer style chunks'.format(sc['cmd_extra_bytes'])}[k]
        delay = {'none': 'none', 'signing': 'the flight stack itself',
                 'hybrid': '{0} ms per command; handshake {1} ms'.format(f(sc['cmd_delay_s'] * 1e3, 3), f(cfgmod.handshake_compute_s(sc) * 1e3, 1)),
                 'pqsig': '{0} ms per command (ML-DSA-44 verify)'.format(f(sc['cmd_delay_s'] * 1e3, 2))}[k]
        arch = {'none': 'unauthenticated stream', 'signing': 'D', 'hybrid': 'B', 'pqsig': 'C'}[k]
        w(f'| {cfgmod.CONFIG_NAMES[k]} | {what} | {delay} | {arch} |')
    w('')
    w('Delays are published cycle counts at the 168 MHz clock of the mission study (`mission/model.py`, data/evidence.csv '
      'rows S2-0032 and S2-0033 and the rows of the mission study cycle table); no cryptographic function is executed by '
      'the relay pair. The rekey interval of the architecture (300 s) is longer than a mission, so no rekey occurs.')
    w('')
    for p in profiles:
        w(f'## 3. Results, {cfgmod.PROFILE_NAMES[p]}')
        w('')
        w('| configuration | missions completed | commands | availability, ACK within 0.5 s, link up [95% CI] | availability, all commands | median round trip ms [95% CI] | 95th percentile ms | added round trip ms [95% CI] | added one way ms (emulated) |')
        w('|---|---|---|---|---|---|---|---|---|')
        for k in cfgmod.CONFIGS:
            if len(summ[(summ.profile == p) & (summ.config == k)]) == 0:
                continue
            ad = 'n/a' if k == 'none' else f'{f(val(p, k, "added_latency_rt_ms"), 1)} [{f(val(p, k, "added_latency_rt_ms", "ci_lo"), 1)}, {f(val(p, k, "added_latency_rt_ms", "ci_hi"), 1)}]'
            ado = 'n/a' if k == 'none' else f(val(p, k, 'added_latency_ow_ms'), 1)
            w(f'| {cfgmod.CONFIG_NAMES[k]} | {f(val(p, k, "missions_completed"), 0)} of {f(val(p, k, "missions"), 0)} | '
              f'{f(val(p, k, "commands"), 0)} | {f(val(p, k, "availability_rt_link_up"), 4)} '
              f'[{f(val(p, k, "availability_rt_link_up", "ci_lo"), 4)}, {f(val(p, k, "availability_rt_link_up", "ci_hi"), 4)}] | '
              f'{f(val(p, k, "availability_rt_all"), 4)} | {f(val(p, k, "latency_rt_median_ms"), 1)} '
              f'[{f(val(p, k, "latency_rt_median_ms", "ci_lo"), 1)}, {f(val(p, k, "latency_rt_median_ms", "ci_hi"), 1)}] | '
              f'{f(val(p, k, "latency_rt_p95_ms"), 1)} | {ad} | {ado} |')
        w('')
        w('_SITL measured except the last column (emulated); intervals are 95 percent cluster bootstrap intervals over missions._')
        w('')
        hk = summ[(summ.profile == p) & (summ.config == 'hybrid')]
        if len(hk):
            w(f'Hybrid session (emulated): median handshake {f(val(p, "hybrid", "handshake_median_s"), 3)} s '
              f'(range {f(val(p, "hybrid", "handshake_median_s", "ci_lo"), 3)} to {f(val(p, "hybrid", "handshake_median_s", "ci_hi"), 3)} s); '
              f'{f(val(p, "hybrid", "teardowns"))} missions had an outage longer than the session timeout, and the median time from the end '
              f'of such an outage to a new session was {f(val(p, "hybrid", "session_recovery_median_s"), 3)} s.')
            w('')
        rec = summ[(summ.profile == p) & (summ.metric == 'command_recovery_median_s')]
        if len(rec):
            w('Median time from the end of the outage to the first accepted acknowledgement (SITL measured; it includes the wait '
              'for the next command of the 1 s stream): ' + '; '.join(
                  f'{cfgmod.CONFIG_NAMES[r.config]} {f(r.value, 2)} s' for r in rec.itertuples()) + '.')
            w('')
        ru = runs[runs.profile == p]
        if len(ru):
            w('Channel utilisation over each run (emulated, both directions, including the time between missions): ' + '; '.join(
                f'{cfgmod.CONFIG_NAMES[r.config]} {f(r.utilisation, 3)}' for r in ru.itertuples()) + '.')
            w('')
        w(f'Figures: `sitl/results/fig_latency_cdf_{p}.svg`, `sitl/results/fig_availability_{p}.svg`, and one timeline per '
          f'configuration `sitl/results/fig_timeline_{p}_<configuration>.svg`.')
        w('')
        w(f'## 4. Comparison with the mission study, {cfgmod.PROFILE_NAMES[p]}')
        w('')
        w('| configuration | quantity | this study | label | mission study (estimated) | error (this study minus study) | verdict |')
        w('|---|---|---|---|---|---|---|')
        for r in comp[comp.profile == p].itertuples():
            rng = '' if not (r.ci_lo == r.ci_lo) else f' [{f(r.ci_lo, 4)}, {f(r.ci_hi, 4)}]'
            w(f'| {cfgmod.CONFIG_NAMES[r.config]} | {r.study_quantity} ({r.metric}) | {f(r.value, 4)}{rng} | {r.label} | '
              f'{f(r.study_estimated, 4)} | {f(r.error, 4)} | {r.verdict} |')
        w('')
        w('Verdict "consistent" means the mission study value lies inside the 95 percent interval of this study; '
          '"no interval" rows give a range of observed values instead of an interval.')
        w('')
    w('## 5. Reading the comparison')
    w('')
    w('- The mission study defines latency as one way delivery of the command to the vehicle; this study measures the round '
      'trip to the flight stack acknowledgement, which adds the acknowledgement air time, the flight stack scheduling and '
      'the queue behind telemetry. The one way columns (emulated) are the closer match to the study definition; the round '
      'trip columns are the stricter, SITL measured quantity.')
    w('- The telemetry load comes from the flight stack: stream rates were set to the drone rates of `mission/traffic.csv` '
      'where the integer stream rate parameters allow it, but each stream group carries more messages than the study '
      'counts, so the channel is busier than in the study.')
    w('- One outage per mission is a forced design, not a Poisson process, so the availability with outages is compared '
      'with the 60 per hour sweep point only as an order of magnitude check.')
    w('')
    w('## 6. Limits')
    w('')
    w('- Phase locking (fixed by a rerun): a first set of runs sent command k exactly k seconds after arming, so every '
      'command of a mission met the periodic telemetry at the same phase and latency differences of tens of milliseconds '
      'were not resolved. `sitl/run_missions.py` now draws a random phase for every command from the run seed, and all '
      'results in this document come from the rerun with that fix (same seeds). The raw files of the first set are kept '
      'in `sitl/raw_run1/` for the record and are not used.')
    w('- Acknowledgement matching: the relay of the recorded runs paired acknowledgements with delivered commands in '
      'order. With signing the flight stack silently discarded some delivered commands (a frame retransmitted by the '
      'emulated link layer arrives after a newer frame and fails the signing timestamp rule), which shifted that order; '
      '`sitl/analyse.py` reassigns each acknowledgement to the command delivered at most 0.3 s before it, and the relay '
      'now does the same.')
    w('- Only the SiK class profile was run; the IEEE 802.15.4 class profile is implemented but has no runs.')
    w('- SITL measured timings come from a host with two shared cores; scheduling noise of the host enters every round trip.')
    w('- The link is an emulation with independent frame loss, a first in first out shared queue and an assumed radio '
      f'buffer of {f(s["queue_limit_bytes"], 0)} B per direction; it is not a radio.')
    w('- Configurations 3 and 4 add bytes and delays only; nothing cryptographic is executed, and the session state machine '
      'is the relay pair, not the flight stack.')
    w('- ArduPilot accepts unsigned messages on its first serial port (SERIAL0, the wired port of this set up), as its '
      'documentation states for USB; the emulated link uses SERIAL1, where signing is enforced.')
    w('- 20 missions per configuration and profile give wide intervals for rare events (teardowns).')
    w('')
    w('## 7. Reproduce')
    w('')
    w('```')
    w('sh sitl/fetch.sh                      # flight stack at the pinned tag, built outside the repository')
    w('sh sitl/run_all.sh                    # all configurations and profiles, about one minute per mission')
    w('python3 -m sitl.analyse && python3 -m sitl.make_doc')
    w('python3 -m unittest discover -s sitl -t .')
    w('```')
    w('')
    with open(os.path.join(ROOT, 'docs', 'SITL_STUDY.md'), 'w') as fh:
        fh.write('\n'.join(L))
    return 0


if __name__ == '__main__':
    sys.exit(main())
