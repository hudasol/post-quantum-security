"""Write docs/SITL_STUDY_R7.md from sitl/results_r7/ (round 7 gateway emulation: Falcon-512 per command, burst loss and
the larger set of 100 missions). Every number is read from a result file. Author: Huda Mueen."""
import json
import os
import sys

import pandas as pd

from . import config_r6 as c6
from . import config_r7 as c7

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RES = os.path.join(HERE, 'results_r7')
DOC = os.path.join(ROOT, 'docs', 'SITL_STUDY_R7.md')
NAMES = {**c6.CONFIG_NAMES, **c7.CONFIG_NAMES}
SET_TITLE = {k: v['title'] for k, v in c7.SETS.items()}


def rd(name):
    p = os.path.join(RES, name)
    return pd.read_csv(p) if os.path.exists(p) else pd.DataFrame()


def name(k):
    return NAMES[k].split(' ', 1)[1]


def f(x, nd=2, sign=False):
    if pd.isna(x):
        return 'not available'
    return f'{x:+.{nd}f}' if sign else f'{x:.{nd}f}'


def summary_table(summ, s):
    g = summ[summ.set == s]
    if len(g) == 0:
        return []

    def val(k, m, nd=3):
        r = g[(g.config == k) & (g.metric == m)]
        if len(r) == 0:
            return 'not applicable'
        r = r.iloc[0]
        return f'{r.value:.{nd}f} [{r.ci_lo:.{nd}f}, {r.ci_hi:.{nd}f}]' if not pd.isna(r.ci_lo) else f'{r.value:.{nd}f}'
    L = ['| configuration | missions | commands | share within 0.5 s | share within 1 s | added round trip (ms) | '
         'missed per mission | handshake (s) |', '|---|---|---|---|---|---|---|---|']
    for k in dict.fromkeys(g.config):
        n = g[(g.config == k) & (g.metric == 'missions')].value
        cm = g[(g.config == k) & (g.metric == 'commands')].value
        L.append(f'| {name(k)} | {int(n.iloc[0])} | {int(cm.iloc[0])} | {val(k, "availability_rt_all")} | '
                 f'{val(k, "availability_rt_all_1s")} | {val(k, "added_latency_rt_ms", 1)} | '
                 f'{val(k, "missed_per_mission", 2)} | {val(k, "handshake_median_s", 2)} |')
    return L


def pairs_table(pm, s):
    g = pm[pm.set == s]
    if len(g) == 0:
        return []
    L = ['| configuration | minus | missed per mission, difference [95% interval] | missions paired | missions differing |',
         '|---|---|---|---|---|']
    for r in g.itertuples():
        L.append(f'| {name(r.config)} | {name(r.minus_config)} | {r.difference:+.2f} [{r.ci_lo:+.2f}, {r.ci_hi:+.2f}] | '
                 f'{int(r.missions_paired)} | {int(r.missions_differing)} |')
    return L


def main():
    summ, pm, lc, bl, rr, hc, dl = (rd(x) for x in ('summary.csv', 'paired_missed.csv', 'loss_change.csv',
                                                    'burst_loss.csv', 'rerun_check.csv', 'host_compute.csv',
                                                    'delays.csv'))
    if len(summ) == 0:
        print('no results')
        return 1
    s7 = c7.load_settings()
    b = c7.burst_params(0.02, s7['burst_mean_frames'])
    L = ['# Gateway emulation with ArduPilot SITL, round 7', '',
         'Author: Huda Mueen. Generated by `sitl/make_doc_r7.py` from `sitl/results_r7/`; do not edit by hand. The round 6 '
         'study (`docs/SITL_STUDY_R6.md`, `sitl/results_r6/`, `sitl/raw_r6/`) is unchanged; round 7 adds three result '
         'sets beside it, each in `sitl/raw_r7/<set>/`.', '',
         'Set up as in round 6: ArduPilot Copter 4.7.2 in software in the loop with its built in vehicle model flies a '
         'scripted mission; the ground station sends one acknowledged COMMAND_LONG per second; a gateway pair executes '
         'the cryptography with pinned libraries in front of the unmodified flight stack (which never runs it); a relay '
         'emulates a SiK class radio with link layer retransmission and one outage per mission; vehicle side compute is '
         'a delay from Ibex cycles at the mission study clock. Labels: shares, round trips and missed commands are SITL '
         'measured; channel counts and handshake times emulated; delays estimated from RTL simulated cycles; host '
         'compute host measured. Intervals: 95 percent bootstrap over missions, paired by seed for differences '
         '(`sitl/analyse_r7.py`). Missed commands per mission: stream commands not acknowledged within 0.5 s, outages '
         'included (the round 6 metric).', '',
         '## Result sets', '',
         f'- falcon20: {SET_TITLE["falcon20"]}. Compared with the round 6 runs on the same seeds.',
         f'- burst20: {SET_TITLE["burst20"]}. The two state loss process (`sitl/linkrelay.py`) moves between a good '
         f'and a bad state once per transmitted frame and loses every frame sent in the bad state: p(good to bad) '
         f'{b["p_gb"]:.5f}, p(bad to good) {b["p_bg"]:.2f}, so the mean frame loss is {b["mean_loss"]:.2f} (the round 6 '
         f'value) and the mean burst {b["mean_burst_frames"]:.0f} frames (`sitl/settings_r7.csv`, an assumption '
         'without a measured SiK source; one value, no sweep). Outages are as in round 6. Compared with the round 6 '
         'runs (and falcon20 for Falcon-512) under independent loss on the same seeds.',
         f'- large100: {SET_TITLE["large100"]}. Missions 0 to 19 repeat the round 6 seeds.', '']
    for s in ('falcon20', 'burst20', 'large100'):
        t = summary_table(summ, s)
        if not t:
            continue
        L += [f'## {s}', '']
        if s == 'falcon20':
            L += ['Falcon-512 rows of this set, with the round 6 rows of the same seeds for reference in the paired '
                  'differences below.', '']
        L += t + ['']
        p = pairs_table(pm, s)
        if p:
            L += ['Paired differences of missed commands per mission:', ''] + p + ['']
    if len(bl):
        tot = bl.frames.sum()
        L += ['## Burst loss process as realised', '',
              f'Over {len(bl)} burst loss runs, {int(bl.burst_lost_frames.sum()):,} of {int(tot):,} transmitted frames '
              f'({bl.burst_lost_frames.sum() / tot:.4f}) were lost to the loss process and {int(bl.outage_lost_frames.sum()):,} '
              f'to outages; {int(bl.bad_state_frames.sum()):,} frames were sent in the bad state (emulated).', '']
    if len(lc):
        L += ['## Burst loss against independent loss', '',
              '| configuration | minus | quantity | value [95% interval] | missions |', '|---|---|---|---|---|']
        for r in lc.itertuples():
            L.append(f'| {name(r.config)} | {name(r.minus_config) if isinstance(r.minus_config, str) and r.minus_config else ""} | '
                     f'{r.metric} | {r.difference:+.2f} [{r.ci_lo:+.2f}, {r.ci_hi:+.2f}] | {int(r.missions_paired)} |')
        L.append('')
    if len(rr):
        L += ['## Reruns of the round 6 seeds', '',
              'Missions 0 to 19 of the larger set use the seeds of round 6 (and of falcon20 for Falcon-512). The flight '
              'stack runs in real time on a shared host, so a rerun is not identical: command phases and outages are '
              'paired, but thread timing differs.', '',
              '| configuration | reference | larger set mean | reference mean | difference [95% interval] |',
              '|---|---|---|---|---|']
        for r in rr.itertuples():
            L.append(f'| {name(r.config)} | {r.reference} | {r.larger_set_mean:.2f} | {r.reference_mean:.2f} | '
                     f'{r.difference:+.2f} [{r.ci_lo:+.2f}, {r.ci_hi:+.2f}] |')
        L.append('')
    if len(dl):
        L += ['## Vehicle side delay of Falcon-512', '', '| name | core | used in runs | cycles | delay (ms) | source |',
              '|---|---|---|---|---|---|']
        for r in dl.drop_duplicates(['name', 'core']).itertuples():
            L.append(f'| {r.name} | {r.core} | {"yes" if r.used_in_runs else "no"} | {r.cycles:,.0f} | {r.delay_ms:.2f} | {r.source} |')
        L.append('')
    if len(hc):
        g = hc.groupby(['set', 'config', 'operation'], sort=False).agg(count=('count', 'sum'), host_mean_ms=('host_mean_ms', 'mean'),
                                                                        host_max_ms=('host_max_ms', 'max'),
                                                                        exceeds=('host_exceeds_rtl_delay', 'sum')).reset_index()
        g = g[g.operation.str.contains('sign_command|verify_command')]
        if len(g):
            L += ['## Host compute of the per command signatures', '',
                  'Ground side signing runs at host speed (host measured); the vehicle side verification is released after '
                  'the RTL derived delay, and the table counts how often the host took longer than that delay.', '',
                  '| set | configuration | operation | count | host mean (ms) | host max (ms) | host above the delay |',
                  '|---|---|---|---|---|---|---|']
            for r in g.itertuples():
                L.append(f'| {r.set} | {name(r.config)} | {r.operation} | {int(r.count):,} | {r.host_mean_ms:.3f} | '
                         f'{r.host_max_ms:.2f} | {int(r.exceeds):,} |')
            L.append('')
    env = {}
    for s in ('falcon20', 'burst20', 'large100'):
        p = os.path.join(HERE, 'raw_r7', s)
        if os.path.isdir(p):
            js = sorted(x for x in os.listdir(p) if x.endswith('_run.json'))
            if js:
                with open(os.path.join(p, js[0])) as fh:
                    env[s] = json.load(fh).get('libraries', {})
    if env:
        L += ['## Libraries of the runs', '']
        for s, lib in env.items():
            L.append(f'- {s}: ' + ', '.join(f'{k} {v}' for k, v in sorted(lib.items())))
        L.append('')
    with open(DOC, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(L))
    print('wrote', DOC)
    return 0


if __name__ == '__main__':
    sys.exit(main())
