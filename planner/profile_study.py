# ---------------------------------------------------------------- profiles
def load_profiles(path=PROFILES):
    """Profiles with flash_kb and ram_kb in planner kB (1000 B), as Fractions."""
    out = []
    with open(path, newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            if not r["flash_bytes"] or not r["ram_bytes"]:
                raise ValueError(f"{r['board']}: total flash and RAM are required")
            p = dict(r)
            p["flash_kb"] = Fraction(int(r["flash_bytes"]), 1000)
            p["ram_kb"] = Fraction(int(r["ram_bytes"]), 1000)
            p["free_flash_kb"] = (Fraction(int(r["free_flash_bytes_derived"]), 1000)
                                  if r["free_flash_bytes_derived"] else None)
            p["free_ram_kb"] = (Fraction(int(r["free_ram_bytes_derived"]), 1000)
                                if r["free_ram_bytes_derived"] else None)
            out.append(p)
    return out


def kb_text(x):
    """Decimal text for a Fraction with a denominator dividing 1000."""
    x = Fraction(x)
    if x.denominator == 1:
        return str(x.numerator)
    s = f"{float(x):.3f}".rstrip("0").rstrip(".")
    if Fraction(s) != x:
        raise ValueError(f"{x} is not exact at three decimals")
    return s


def profile_fleet(base, profiles, rng, free_range):
    """Copy of the base fleet with memory replaced by a profile draw.

    Each device gets one profile, chosen with equal shares (synthetic mix).
    Total flash and RAM are the published totals. Free memory: the published
    derived value when the profile has one; otherwise, when free_range is None,
    blank (not known); otherwise total times a uniform share in free_range
    (assumption), floored to whole kB. A device whose base free memory was blank
    stays blank, so the share of unknown free memory matches round 3. All other
    fields are kept from the base fleet."""
    out = []
    for d in base:
        p = profiles[rng.randrange(len(profiles))]
        e = dict(d)
        e["flash_kb"] = kb_text(p["flash_kb"])
        e["ram_kb"] = kb_text(p["ram_kb"])
        e["core"] = p["core"].replace(",", " ")
        e["notes"] = "SYNTHETIC profile " + p["board"].replace(",", " ")
        for free, total in (("free_flash_kb", "flash_kb"), ("free_ram_kb", "ram_kb")):
            share = rng.uniform(*free_range) if free_range else None
            if d[free] == "":
                e[free] = ""
            elif p[free] is not None:
                e[free] = kb_text(p[free])
            elif free_range is None:
                e[free] = ""
            else:
                e[free] = str(int(p[total] * Fraction(share)))
        out.append(e)
    return out


# -------------------------------------------------------------- thresholds
def threshold_ranges(path=EVIDENCE):
    """(low, high) in bytes for each memory threshold, from published rows,
    with the derivation of docs/PLANNER_RULES.md, and the row ids used."""
    with open(path, newline="", encoding="utf-8") as fh:
        ev = {r["id"]: r for r in csv.DictReader(fh)}
    sig = [ev[i] for i in SIG_ROWS]
    kem = [ev[i] for i in KEM_ROWS]
    for r in sig:
        assert r["parameter_set"] == "ML-DSA-44" and r["operation"] == "verify", r["id"]
    for r in kem:
        assert r["parameter_set"] == "ML-KEM-768" and r["operation"] == "decaps", r["id"]
    sf = [int(r["flash_or_code_bytes"]) + fs.HEADER for r in sig]
    sr = [int(r["stack_bytes"]) + fs.SIG_BUFFERS for r in sig]
    kf = [int(r["flash_or_code_bytes"]) for r in kem]
    kr = [int(r["stack_bytes"]) + KEM_BUFFERS for r in kem]
    return {"sig_flash_kb": (min(sf), max(sf), SIG_ROWS), "sig_ram_kb": (min(sr), max(sr), SIG_ROWS),
            "kem_flash_kb": (min(kf), max(kf), KEM_ROWS), "kem_ram_kb": (min(kr), max(kr), KEM_ROWS)}


def draw_params(rng, ranges, **fixed):
    """Parameters with each memory threshold uniform in its byte range,
    converted to kB of 1000 B and rounded up as in docs/PLANNER_RULES.md."""
    kw = {k: Fraction(math.ceil(rng.uniform(lo, hi) / 1000)) for k, (lo, hi, _) in ranges.items()}
    kw.update(fixed)
    return Parameters(**kw)


# -------------------------------------------------------------- statistics
def percentile(xs, q):
    s = sorted(xs)
    k = (len(s) - 1) * q
    f = math.floor(k)
    c = min(f + 1, len(s) - 1)
    return s[f] + (s[c] - s[f]) * (k - f)


def median(xs):
    return percentile(xs, 0.5)


def bootstrap_median_ci(xs, seed=SEED, reps=2000):
    """Bootstrap 95 percent interval for the median."""
    rng = random.Random(seed)
    meds = [median([xs[rng.randrange(len(xs))] for _ in xs]) for _ in range(reps)]
    return percentile(meds, 0.025), percentile(meds, 0.975)


def wilson(k, n, z=1.959963984540054):
    """Wilson 95 percent interval for a proportion k of n."""
    if n == 0:
        return (0.0, 1.0)
    p = k / n
    den = 1 + z * z / n
    mid = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return max(0.0, mid - half), min(1.0, mid + half)


# ------------------------------------------------------------------ Mosca
def exposed(x, y, horizon_year, today=TODAY):
    """Mosca condition: data lifetime x plus migration time y exceeds the
    years left until the policy horizon (z = horizon_year - today)."""
    return x + y > horizon_year - today


def mosca_probability(x, horizons, rng, draws=4000, migration=MIGRATION):
    """P(exposure) for a fixed data lifetime x, with migration time uniform in
    migration and the horizon drawn from the list of policy years."""
    hit = 0
    for _ in range(draws):
        if exposed(x, rng.uniform(*migration), horizons[rng.randrange(len(horizons))]):
            hit += 1
    return hit / draws


def mosca_overall(horizons, rng, draws=20000):
    hit = 0
    for _ in range(draws):
        if exposed(rng.uniform(*DATA_LIFETIME), rng.uniform(*MIGRATION),
                   horizons[rng.randrange(len(horizons))]):
            hit += 1
    return hit, draws


def sobol(horizon_lo, horizon_hi, n=SOBOL_N, seed=SEED):
    """First order and total Sobol indices of the exposure indicator with
    respect to data lifetime, migration time and horizon year (uniform)."""
    import numpy as np
    from SALib.analyze import sobol as sa
    from SALib.sample import sobol as ss
    problem = {"num_vars": 3, "names": ["data_lifetime_years", "migration_years", "horizon_year"],
               "bounds": [list(DATA_LIFETIME), list(MIGRATION), [horizon_lo, horizon_hi]]}
    X = ss.sample(problem, n, calc_second_order=False, seed=seed)
    Y = np.array([1.0 if exposed(a, b, c) else 0.0 for a, b, c in X])
    Si = sa.analyze(problem, Y, calc_second_order=False, seed=seed)
    rows = []
    for i, name in enumerate(problem["names"]):
        rows.append({"input": name, "low": problem["bounds"][i][0], "high": problem["bounds"][i][1],
                     "S1": float(Si["S1"][i]), "S1_conf": float(Si["S1_conf"][i]),
                     "ST": float(Si["ST"][i]), "ST_conf": float(Si["ST_conf"][i])})
    return rows, float(Y.mean()), len(Y)


def flip_lifetime(migration, horizon_year, today=TODAY):
    """Data lifetime above which the Mosca condition holds."""
    return horizon_year - today - migration


# ------------------------------------------------------------- properties
def worse(a, b):
    """True when class b is a worse outcome than class a on the memory scale
    FIRMWARE_UPDATE < HYBRID < HARDWARE_REPLACEMENT (other classes unranked)."""
    return a in RANK and b in RANK and RANK[b] > RANK[a]


def limit_violations(devices, results, params):
    """Devices given FIRMWARE_UPDATE or HYBRID whose free memory is below the
    need in force (fleetstudy.violations) or whose free memory exceeds the
    stated total, which would mean the input broke the published limit."""
    bad = list(fs.violations(devices, results, params))
    for d in devices:
        for free, total in (("free_flash_kb", "flash_kb"), ("free_ram_kb", "ram_kb")):
            if d[free] != "" and Fraction(d[free]) > Fraction(d[total]):
                bad.append(d["device_id"])
    return sorted(set(bad))


