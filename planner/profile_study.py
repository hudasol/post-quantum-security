def replace_section(doc_text, section_text):
    """doc_text with the marked section replaced, or appended when absent."""
    block = START + "\n" + section_text.rstrip("\n") + "\n" + END + "\n"
    if START in doc_text and END in doc_text:
        a = doc_text.index(START)
        b = doc_text.index(END) + len(END)
        rest = doc_text[b:].lstrip("\n")
        return doc_text[:a] + block + rest
    return doc_text.rstrip("\n") + "\n\n" + block


def refresh_doc(doc=DOC, section=SECTION):
    """Write the saved section into docs/PLANNER_STUDY.md (no recomputation).
    Called by fleetstudy.py after it rewrites that file."""
    if not os.path.exists(section):
        return False
    with open(section, encoding="utf-8") as fh:
        sec = fh.read()
    with open(doc, encoding="utf-8") as fh:
        text = fh.read()
    with open(doc, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(replace_section(text, sec))
    return True


def main():
    t0 = time.time()
    profiles = load_profiles()
    ranges = threshold_ranges()
    scen = fs.scenarios()
    base = fs.make_fleet(N)  # round 3 fleet, seed 20261016 + 1000
    # A. reproduce round 3
    with open(os.path.join(RES, "scenario_range.csv"), newline="", encoding="utf-8") as fh:
        r3 = [r for r in csv.DictReader(fh) if r["devices"] == str(N)][0]
    rep = {k: hr(base, p) for k, _, _, p in scen}
    lo_k, hi_k = min(rep, key=rep.get), max(rep, key=rep.get)
    assert (rep[lo_k], rep[hi_k]) == (int(r3["hr_low"]), int(r3["hr_high"])), (rep, r3)
    # B. published totals only, free memory not known
    rng = random.Random(SEED)
    only = profile_fleet(base, profiles, rng, None)
    rows_b = []
    for k, _, _, p in scen:
        c = fs.counts(fs.classify_devices(only, p))
        rows_b.append({"scenario": k, "free_memory": "not known (published totals only)", **c})
    # C. one seeded profile fleet with the main free share assumption
    rng = random.Random(SEED)
    main_fleet = profile_fleet(base, profiles, rng, FREE_RANGES[FREE_MAIN])
    rows_c, per_board = [], []
    for k, _, _, p in scen:
        res = fs.classify_devices(main_fleet, p)
        c = fs.counts(res)
        lo, hi = wilson(c[HARDWARE_REPLACEMENT], N)
        rows_c.append({"scenario": k, "hr": c[HARDWARE_REPLACEMENT], "hr_share": c[HARDWARE_REPLACEMENT] / N,
                       "wilson_low": lo, "wilson_high": hi, "round3_hr": rep[k],
                       "violations": len(limit_violations(main_fleet, res, p)), **c})
        for b in profiles:
            idx = [i for i, d in enumerate(main_fleet) if d["notes"] == "SYNTHETIC profile " + b["board"].replace(",", " ")]
            n_hr = sum(1 for i in idx if res[i].cls == HARDWARE_REPLACEMENT)
            per_board.append({"scenario": k, "board": b["board"], "devices": len(idx), "hr": n_hr,
                              "hr_share": n_hr / len(idx) if idx else 0.0})
    changed_main = sum(1 for a, b in zip(fs.classify_devices(main_fleet, dict((k, p) for k, _, _, p in scen)["stack_asm"]),
                                         fs.classify_devices(main_fleet, dict((k, p) for k, _, _, p in scen)["reference_c"]))
                       if a.cls != b.cls)
    # D. Monte Carlo
    mc = []
    rng_t = random.Random(SEED + 1)
    for i in range(DRAWS):
        p_unc = draw_params(rng_t, ranges)
        mc.append({"draw": i, "seed": SEED + 1, "fleet": "synthetic", "thresholds": "uncertain",
                   "hr_share": hr(base, p_unc) / N})
        fleet = profile_fleet(base, profiles, random.Random(SEED + 1000 + i), FREE_RANGES[FREE_MAIN])
        for k, _, _, p in scen:
            mc.append({"draw": i, "seed": SEED + 1000 + i, "fleet": "profile", "thresholds": k,
                       "hr_share": hr(fleet, p) / N})
        mc.append({"draw": i, "seed": SEED + 1000 + i, "fleet": "profile", "thresholds": "uncertain",
                   "hr_share": hr(fleet, p_unc) / N})
    for k, _, _, p in scen:
        mc.append({"draw": 0, "seed": fs.BASE_SEED + N, "fleet": "synthetic", "thresholds": k,
                   "hr_share": rep[k] / N})
    summary = []
    for fleet in ("synthetic", "profile"):
        for k in ("stack_asm", "speed_asm", "portable_c", "reference_c", "uncertain"):
            v = [r["hr_share"] for r in mc if r["fleet"] == fleet and r["thresholds"] == k]
            if len(v) < 2:
                summary.append({"fleet": fleet, "thresholds": k, "draws": len(v), "median": v[0],
                                "p2_5": v[0], "p97_5": v[0], "median_ci_low": v[0], "median_ci_high": v[0]})
                continue
            cl, ch = bootstrap_median_ci(v)
            summary.append({"fleet": fleet, "thresholds": k, "draws": len(v), "median": median(v),
                            "p2_5": percentile(v, 0.025), "p97_5": percentile(v, 0.975),
                            "median_ci_low": cl, "median_ci_high": ch})
    # E. free share sensitivity
    sens = []
    for name, fr in FREE_RANGES.items():
        fl = profile_fleet(base, profiles, random.Random(SEED), fr)
        for k, _, _, p in scen:
            sens.append({"free_range": name, "low": fr[0], "high": fr[1], "scenario": k, "hr": hr(fl, p)})
    # F. Mosca
    tl = pt.load()
    horizons = pt.completion_years(tl)
    h_rows = pt.horizon_rows(tl)
    hit, nd = mosca_overall(horizons, random.Random(SEED))
    p_all = hit / nd
    w_all = wilson(hit, nd)
    sob, sob_mean, sob_n = sobol(min(horizons), max(horizons) + 1)
    rngc = random.Random(SEED)
