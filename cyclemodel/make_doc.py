"""Generate docs/CYCLE_MODEL.md from the result files. Every number in the document comes from
cyclemodel/results/*.csv. Validation errors are written before any modelled value."""
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from cyclemodel import model as M  # noqa: E402

DOC = os.path.join(M.REPO, 'docs', 'CYCLE_MODEL.md')


def f1(x):
    return f'{x:.1f}'


def big(x):
    return f'{int(round(x)):,}'.replace(',', ' ')


def table(header, rows):
    out = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out)


def err_rows(summ, model, subsets):
    out = []
    for s in subsets:
        r = summ[(summ['model'] == model) & (summ['subset'] == s)]
        if r.empty:
            continue
        r = r.iloc[0]
        out.append([s, int(r.n), f'{f1(r.median_abs_pct)} ({f1(r.median_abs_ci_lo)} to {f1(r.median_abs_ci_hi)})',
                    f1(r.worst_abs_pct), f'{f1(r.median_signed_pct)} ({f1(r.median_signed_ci_lo)} to {f1(r.median_signed_ci_hi)})'])
    return out


def build():
    R = M.RES
    summ = pd.read_csv(os.path.join(R, 'error_summary.csv'))
    rows = pd.read_csv(os.path.join(R, 'matched_rows.csv'))
    val = pd.read_csv(os.path.join(R, 'tracer_validation.csv'))
    costs = pd.read_csv(os.path.join(R, 'fitted_costs.csv'))
    sv = pd.read_csv(os.path.join(R, 'sign_variability.csv'))
    bp = pd.read_csv(os.path.join(R, 'board_predictions.csv'))
    ext = pd.read_csv(os.path.join(R, 'external_check.csv'))
    cfg = dict(pd.read_csv(os.path.join(R, 'config.csv'))[['key', 'value']].values)
    split = pd.read_csv(os.path.join(R, 'split.csv'))
    hdr = ['subset', 'n rows', 'median abs error, percent (95% CI)', 'worst abs error, percent', 'median signed error, percent (95% CI)']
    subsets = ['test, all', 'test, excluding sign', 'test, NTT heavy', 'test, hash heavy', 'test, clean C', 'test, assembly (m4f variants)',
               'test, keygen', 'test, encaps', 'test, decaps', 'test, sign', 'test, verify', 'train, all']
    fit_test = summ[(summ['model'] == 'fitted') & (summ['subset'] == 'test, all')].iloc[0]
    ap_test = summ[(summ['model'] == 'apriori') & (summ['subset'] == 'test, all')].iloc[0]
    base_test = summ[(summ['model'] == 'baseline') & (summ['subset'] == 'test, all')].iloc[0]
    n_val_fail = int((~val['passed'].astype(bool)).sum())
    test_bins = sorted(split[split['half'] == 'test']['binary'].unique())
    train_bins = sorted(split[split['half'] == 'train']['binary'].unique())
    worst = rows[rows['half'] == 'test'].assign(a=lambda d: d['err_pct_fitted'].abs()).sort_values('a', ascending=False).head(3)

    L = []
    A = L.append
    A('# Trace driven cycle model for Cortex-M4 post quantum code')
    A('')
    A('Author: Huda Mueen. Generated by `cyclemodel/make_doc.py` (run `python3 cyclemodel/run_all.py`); do not edit by hand.')
    A('')
    A('Evidence labels used here: **published** (pqm4 and ePrint 2026/1333 rows of `data/evidence.csv`), '
      '**emulated** (instruction class counts from Unicorn traces of images built here), **modelled** (cycle '
      'predictions, always with the validation error beside them), **assumption** (a priori per class costs, unverified). '
      f'Seed {M.SEED} for every random step.')
    A('')
    A('## 1. Validation first')
    A('')
    A('### 1.1 Tracer checks (emulated)')
    A('')
    A(table(['check', 'passed', 'detail'], [[r.check, r.passed, r.detail] for r in val.itertuples()]))
    A('')
    A(f'Failed tracer checks: {n_val_fail}. The block level count includes instructions skipped by a failed IT '
      'condition; the instruction hook of Unicorn does not see them. The last check confirms that every difference '
      'between the two counts lies inside an IT block, so the counts agree apart from that stated assumption.')
    A('')
    A('### 1.2 Held out error of the cycle models (modelled against published)')
    A('')
    A(f'Split: {len(split)} matched pqm4 rows from {len(train_bins) + len(test_bins)} binaries; the split is by binary '
      '(parameter set and implementation), so no test row shares a binary with a training row. Training binaries: '
      + ', '.join(train_bins) + '. Test binaries: ' + ', '.join(test_bins) + '. Recorded in `cyclemodel/results/split.csv`.')
    A('')
    A(f'Headline (test half, n={int(fit_test.n)}): fitted model median absolute error {f1(fit_test.median_abs_pct)} percent '
      f'(95% CI {f1(fit_test.median_abs_ci_lo)} to {f1(fit_test.median_abs_ci_hi)}), worst {f1(fit_test.worst_abs_pct)} percent, '
      f'median signed error {f1(fit_test.median_signed_pct)} percent. A priori model (unverified costs): median absolute '
      f'{f1(ap_test.median_abs_pct)} percent, worst {f1(ap_test.worst_abs_pct)} percent, median signed {f1(ap_test.median_signed_pct)} percent. '
      f'Baseline of one cycle per instruction: median absolute {f1(base_test.median_abs_pct)} percent, worst {f1(base_test.worst_abs_pct)} percent, '
      f'median signed {f1(base_test.median_signed_pct)} percent.')
    A('')
    A('Caveat on these intervals: the bootstrap resamples rows as if independent, but rows cluster by binary (three '
      'operations each) and every test binary has a sibling of the same implementation in training. The intervals are '
      'therefore too narrow, and the result shows interpolation within one code base, not transfer to new code or silicon.')
    A('')
    for model, title in (('fitted', 'Fitted model (non negative least squares on the training half)'),
                         ('reduced', 'Reduced fitted model (four feature groups; sensitivity check)'),
                         ('apriori', 'A priori model (per class costs are unverified assumptions)'),
                         ('baseline', 'Baseline: one cycle per executed instruction')):
        A(f'**{title}**')
        A('')
        A(table(hdr, err_rows(summ, model, subsets)))
        A('')
    A('Family: an operation is "hash heavy" when at least half of its traced instructions run inside Keccak functions '
      '(symbol names containing "keccak"), otherwise "NTT heavy". Intervals are bootstrap 95 percent intervals over rows '
      f'({M.N_BOOT} resamples); with three to nine rows per subgroup they are wide and the subgroup results are weak evidence.')
    A('')
    A('Largest held out errors of the fitted model:')
    A('')
    A(table(['row', 'binary', 'operation', 'published cycles', 'modelled cycles', 'error, percent'],
            [[r.id, f'{r.parameter_set} {r.implementation}', r.operation, big(r.cycles_published), big(r.cycles_modelled_fitted),
              f1(r.err_pct_fitted)] for r in worst.itertuples()]))
    A('')
    fails = []
    if ap_test.median_abs_pct > 10:
        fails.append(f'the a priori model misses by a median of {f1(ap_test.median_abs_pct)} percent on the test half')
    if fit_test.worst_abs_pct > 15:
        fails.append(f'the fitted model has a held out worst case of {f1(fit_test.worst_abs_pct)} percent')
    A('Failures stated plainly: ' + ('; '.join(fails) + '.' if fails else 'none above the 10 percent (median) and 15 percent (worst) marks used here.'))
    A('')
    red_test = summ[(summ['model'] == 'reduced') & (summ['subset'] == 'test, all')].iloc[0]
    sign_fit = summ[(summ['model'] == 'fitted') & (summ['subset'] == 'test, sign')].iloc[0]
    nosign = summ[(summ['model'] == 'fitted') & (summ['subset'] == 'test, excluding sign')].iloc[0]
    pub = M.published_pqm4()
    sign_runs = sorted(set(pub[pub['operation'] == 'sign']['compiler_flags_or_notes'].str.extract(r'mean of (\d+) executions')[0].dropna()))
    pq_sv = sv[sv['source'] == 'pqm4']
    h = bp[bp['target'] != 'pqm4 B0']
    gap = (h['cycles_modelled'] / h['cycles_modelled_reduced'] - 1) * 100
    A(f'Signing is the weak part: held out sign rows have a median absolute error of {f1(sign_fit.median_abs_pct)} percent '
      f'(worst {f1(sign_fit.worst_abs_pct)}), against {f1(nosign.median_abs_pct)} percent (worst {f1(nosign.worst_abs_pct)}) for all other '
      f'operations. Published sign values are means over {", ".join(sign_runs)} runs (row notes); the traces use '
      f'{int(pq_sv["n_messages"].min())} messages per binary, and the per message coefficient of variation of the traced signing cost is '
      f'{f1(pq_sv["cv_pct"].min())} to {f1(pq_sv["cv_pct"].max())} percent (section 5.2), so the standard error of the traced mean is '
      f'{f1((pq_sv["cv_pct"] / pq_sv["n_messages"] ** 0.5).min())} to {f1((pq_sv["cv_pct"] / pq_sv["n_messages"] ** 0.5).max())} percent. '
      'The sign error is therefore not attributable to the per class costs alone.')
    A('')
    full = costs[~costs['feature'].str.startswith('reduced')]
    odd = [f'{r.feature} {r.cost_fitted_cycles:.2g}' for r in full.itertuples() if r.cost_fitted_cycles > 3.5 or 0 < r.cost_fitted_cycles < 0.5]
    zero = [r.feature for r in full.itertuples() if r.cost_fitted_cycles == 0]
    n_train = int((split['half'] == 'train').sum())
    A(f'The {len(full)} feature fitted model gives costs that do not read as cycle costs (section 4; above 3.5 or below 0.5 cycles: '
      f'{", ".join(odd) or "none"}; exactly zero: {", ".join(zero) or "none"}), a sign of overfitting with {n_train} training rows. '
      'The reduced model, added after this '
      f'was seen, has costs near plausible values and a held out median absolute error of {f1(red_test.median_abs_pct)} percent (worst '
      f'{f1(red_test.worst_abs_pct)}). On the pqm4 test rows the two agree closely; on code whose instruction mix lies outside the training rows '
      f'(the mlkem-native and mldsa-native harness) the full model is {f1(gap.min())} to {f1(gap.max())} percent above the reduced one (section 5.1).')
    A('')
    A('Figures: `docs/figures/cyclemodel/predicted_vs_published.png` (log scale, train and test marked) and '
      '`docs/figures/cyclemodel/error_by_family.png`, both labelled "modelled; validation error shown" with the seed.')
    A('')
    A('### 1.3 External check without refitting (ePrint 2026/1333, Cortex-M33)')
    A('')
    A('The rows S10C-* name three libraries. stm32pqc-lowram is a vendor precompiled binary (not buildable from source). '
      'wolfssl-lowram is a modified wolfSSL fork whose build the paper\'s benchmark manifest describes as having no single '
      'proven command, and its low RAM configuration is not stated in the paper, so it was not built. pqcrystals-lowram '
      'is open source (dilithium-lowram, tag crypto-benchmark-0.0.16, commit '
      f'{cfg.get("dilithium_lowram_commit", "")}); its key expansion from a seed was built for Cortex-M4 with -Ofast and traced. '
      'Signing was not compared: the paper uses a crafted test vector set whose inputs were not reproduced here.')
    A('')
    if 'cycles_published' in ext.columns:
        A(table(['row', 'set', 'published statistic', 'published cycles (M33)', 'modelled cycles (M4 model)', '95% PI (modelled)', 'error, percent', 'inside PI'],
                [[r.id, r.parameter_set, r.statistic_published, big(r.cycles_published), big(r.cycles_modelled_fitted),
                  f'{big(r.pi95_lo_modelled)} to {big(r.pi95_hi_modelled)}', f1(r.err_pct_fitted), r.inside_pi95] for r in ext.itertuples()]))
        A('')
        A('This check crosses three differences at once: core (Cortex-M33 against the Cortex-M4 the model was fitted on), '
          'memory system (160 MHz with flash wait states hidden by caches against zero wait states), and compiler (GCC 14.2.1 '
          'with unstated flags against GCC 13.2.1 with -Ofast). Agreement or disagreement here cannot be assigned to any one of them.')
    A('')
    A('## 2. Method')
    A('')
    nr = pd.read_csv(os.path.join(R, 'traces.csv')).groupby(['source', 'parameter_set', 'operation']).size()
    kem_n = sorted(set(nr.loc['pqm4'].loc[lambda s: s.index.get_level_values(0).str.startswith('ML-KEM')] // 3))
    dsa_n = sorted(set(nr.loc['pqm4'].loc[lambda s: s.index.get_level_values(0).str.startswith('ML-DSA')] // 3))
    h_n = sorted(set(nr.loc['bench_mcu_harness']))
    A('1. Images. `cyclemodel/build_images.sh` builds, outside the repository, the pqm4 speed binaries for PLATFORM=mps2-an386 at commit '
      f'{cfg.get("pqm4_commit", "")} (ML-KEM-512/768/1024 clean, m4fspeed, m4fstack with {", ".join(map(str, kem_n))} iterations; '
      f'ML-DSA-44/65/87 clean, m4f, m4fstack with {", ".join(map(str, dsa_n))} iterations, each iteration a new key pair and message), '
      'the repository harness `bench/mcu` (mlkem-native v2.0.0 and mldsa-native v2.0.0 at the pins of `bench/mcu/fetch_libs.sh`, -O2, BENCH_ITERS=10; '
      f'every call of a target function in the harness run is traced, including its untimed correctness and stack measurement calls, giving '
      f'{min(h_n)} to {max(h_n)} calls per operation), and the external check image.')
    A('2. Tracing. `cyclemodel/tracer.py` loads each ELF into Unicorn with the mps2-an386 memory map (peripherals as RAM reading zero, '
      'semihosting stops the run), runs from the reset vector, and counts executed instructions by class between entry to and return from '
      'each target function (crypto_kem_keypair, crypto_kem_enc, crypto_kem_dec, crypto_sign_keypair, crypto_sign_ctx, crypto_sign_open_ctx and '
      'the harness equivalents). Classes: ALU, multiply, multiply accumulate, divide, load, store (LDRD and STRD with an extra word count), '
      'LDM/STM with register count, unconditional branch, conditional branch taken and not taken (from the address of the next block), '
      'writes to PC, IT, FPU moves, FPU loads and stores, FPU arithmetic, other.')
    A('3. Models. Baseline (one cycle per instruction); a priori (per class costs, section 4); fitted (non negative least squares on the training '
      'half, each row weighted by the inverse of its published value so that relative error is minimised).')
    A('4. Errors. Percent error is (modelled minus published) divided by published. Bootstrap 95 percent intervals over rows.')
    A('5. Prediction intervals. With e the held out relative error, the true value is modelled / (1 + e); the 2.5 and 97.5 percentiles of the '
      f'{int(fit_test.n)} held out errors give the bounds. With so few held out rows these percentiles are close to the extreme errors.')
    A('')
    A('## 3. Assumptions and limits')
    A('')
    A(f'* Toolchain differs: images here use {cfg.get("toolchain_used", "")}; the published pqm4 numbers used '
      f'{cfg.get("toolchain_published_pqm4", "")}. Code generation differences enter the error directly; for clean C code this can be large.')
    A('* No wait state, cache or bus contention model. The pqm4 benchmark clock modes use zero flash wait states (data/raw/S6_pqm4_config.md); '
      'the model therefore describes a zero wait state Cortex-M4 only. The board that produced pqm4 benchmarks.csv is not recorded.')
    A('* pqm4 counts cycles with SysTick (core clock, 24 bit with overflow count); the measured window includes call overhead and two timer reads. '
      'SysTick overflow interrupts (one per 2^24 cycles) run on the board but not in the emulation.')
    A('* Signing is variable time (rejection sampling). The published pqm4 sign value is a mean over its runs; the model uses the mean of '
      f'{", ".join(map(str, dsa_n))} traced messages with different keys. Section 5.2 gives the spread.')
    A('* The tracer counts IT predicated instructions with a failed condition as executed; it does not model pipelining of neighbouring loads, '
      'register dependencies, branch target alignment or the FPU pipeline.')
    A('* The a priori costs could not be checked against the Arm Cortex-M4 Technical Reference Manual: the fetch of the instruction timing page '
      'was refused on 2026-10-20 and not retried. They are listed as unverified assumptions.')
    A('* The fitted costs are not physical cycle costs. With 12 features and few training rows, the non negative fit can trade one class against '
      'another; read them as a calibration, not as timing facts.')
    A('* Randomness is deterministic (fixed seed generators of each code base); inputs differ from the published runs. A second full run '
      'of `cyclemodel/run_all.py` on 2026-10-20 reproduced every instruction count; the ELF hashes in traces.csv changed after a rebuild '
      '(the pqm4 build is not byte reproducible), so the hashes identify a build, not the source.')
    A('')
    A('## 4. Modelled values: per class costs')
    A('')
    A(f'Labels: cost_fitted is modelled (seed {M.SEED}, held out median absolute error {f1(fit_test.median_abs_pct)} percent); cost_apriori is an unverified assumption.')
    A('')
    A(table(['feature', 'tracer classes', 'fitted cost, cycles (modelled)', 'a priori cost, cycles (assumption, unverified)'],
            [[r.feature, r.classes, f'{r.cost_fitted_cycles:.3g}',
              '' if pd.isna(r.cost_apriori_cycles_assumption) else f'{float(r.cost_apriori_cycles_assumption):g}'] for r in costs.itertuples()]))
    A('')
    A('## 5. Modelled values: signing spread and board predictions')
    A('')
    A('### 5.1 Board predictions (pre registered, modelled)')
    A('')
    A(f'Fitted model; 95 percent prediction interval from the held out errors (median absolute {f1(fit_test.median_abs_pct)} percent, worst '
      f'{f1(fit_test.worst_abs_pct)} percent). Target: a Cortex-M4 at zero flash wait states. Written to `cyclemodel/results/board_predictions.csv` '
      'before any board session; a later board run should compare against these values without refitting.')
    A('')
    A('The harness rows are extrapolations: their instruction mix (share of each feature) lies outside the range of the training rows '
      'for the features listed in the column `extrapolation_flags` of the CSV, and the full and reduced fitted models disagree there. '
      'For those rows the pre registered range should be the envelope of both models\' 95 percent prediction intervals (last column). '
      'The pqm4 B0 rows lie inside the training mix apart from the flags shown. Signing values are means over the traced messages; a board '
      'mean over few messages carries the extra sampling spread of section 5.2.')
    A('')
    A(table(['target', 'set', 'implementation', 'operation', 'fitted (modelled)', '95% PI fitted', 'reduced (modelled)', 'envelope of both PIs', 'outside training mix'],
            [[r.target, r.parameter_set, r.implementation, r.operation, big(r.cycles_modelled),
              f'{big(r.pi95_lo_modelled)} to {big(r.pi95_hi_modelled)}', big(r.cycles_modelled_reduced),
              f'{big(r.pi95_envelope_lo_modelled)} to {big(r.pi95_envelope_hi_modelled)}',
              'none' if r.extrapolation_flags == 'none' else str(r.extrapolation_flags).count(';') + 1]
             for r in bp.itertuples()]))
    A('')
    A('Last column: number of features whose share lies outside the training range (names in the CSV).')
    A('')
    A('### 5.2 Signing spread over several messages (modelled)')
    A('')
    A(table(['source', 'set', 'implementation', 'messages', 'mean modelled cycles', 'sd', 'min', 'max', 'coefficient of variation, percent'],
            [[r.source, r.parameter_set, r.implementation, r.n_messages, big(r.cycles_modelled_mean), big(r.cycles_modelled_sd),
              big(r.cycles_modelled_min), big(r.cycles_modelled_max), f1(r.cv_pct)] for r in sv.itertuples()]))
    A('')
    A('## 6. Provenance')
    A('')
    A(table(['item', 'value'], [[k, str(v).replace('|', '/')] for k, v in cfg.items()]))
    A('')
    A('Unverified items: all a priori per class costs in `cyclemodel/model.py` (A_PRIORI). Refused fetch: the Arm Cortex-M4 TRM instruction '
      'timing page named in the table above. Published values come from `data/evidence.csv` (rows S2-* for pqm4, S10C-* for ePrint 2026/1333; '
      'see their retrieval columns). The dilithium-lowram tag was read from the manifest of the paper\'s released benchmark software '
      '(github.com/sebastien-riou/crypto-benchmark, setup_manifest.py), retrieved 2026-10-20.')
    A('')
    A('Files: `cyclemodel/results/` (traces.csv, traces_external.csv, tracer_validation.csv, split.csv, matched_rows.csv, fitted_costs.csv, '
      'error_summary.csv, sign_variability.csv, external_check.csv, board_predictions.csv, config.csv), `docs/figures/cyclemodel/`, tests in '
      '`cyclemodel/tests/` (python3 -m unittest discover -s cyclemodel/tests -t .).')
    A('')
    return '\n'.join(L)


def main():
    text = build()
    with open(DOC, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote', DOC)


if __name__ == '__main__':
    main()
