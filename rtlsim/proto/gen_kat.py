#!/usr/bin/env python3
"""Write kat.h for the protocol benchmark (rtlsim/proto/sw/proto_bench.c). Author: Huda Mueen.

The header holds the domain labels of the session glue and known answers computed on the host with the
Python standard library (hashlib), so that the simulated code is checked against independent values:
  - SHA-256 of a fixed 60 byte input (first 48 bits, as the MAVLink 2 signing tag uses),
  - the MAVLink 2 signing tag over fixed fields, computed with the formula of the MAVLink message signing
    guide (https://mavlink.io/en/guide/message_signing.html, read 2026-10-28):
    sha256_48(secret_key + header + payload + CRC + link-ID + timestamp), timestamp as 6 bytes,
    little endian as the MAVLink C library serialises it,
  - the SHAKE256 key derivation of the session designs over fixed inputs.
Research benchmark support; no cryptographic primitive is implemented here.
Usage: gen_kat.py <output kat.h>
"""
import hashlib
import sys

LABELS = {
    "LABEL_ID": b"r6 identity",
    "LABEL_TH": b"r6 transcript",
    "LABEL_KDF": b"r6 session key",
    "LABEL_CG": b"r6 confirm ground",
    "LABEL_CV": b"r6 confirm vehicle",
}

SHA_IN = bytes((i * 7 + 3) & 0xFF for i in range(60))
TAG_KEY = bytes(range(32))
TAG_HEADER = bytes([0xFD, 48, 0x01, 0x00, 0x05, 0x01, 0x01, 0x4C, 0x00, 0x00])
TAG_PAYLOAD = bytes((i * 13 + 1) & 0xFF for i in range(48))
TAG_CRC = bytes([0x34, 0x12])
TAG_LINK_ID = 1
TAG_TIMESTAMP = 0x00002A0000001234
KDF_SSX = bytes(range(32))
KDF_SSKEM = bytes(0x40 + i for i in range(32))
KDF_TH = bytes(0x80 + i for i in range(32))


def mavlink_tag(key, header, payload, crc, link_id, timestamp):
    """First 6 bytes of SHA-256 over the fields in the order of the signing guide."""
    data = key + header + payload + crc + bytes([link_id]) + timestamp.to_bytes(8, "little")[:6]
    return hashlib.sha256(data).digest()[:6]


def kdf(ssx, sskem, th):
    return hashlib.shake_256(LABELS["LABEL_KDF"] + ssx + sskem + th).digest(32)


def carray(name, data):
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{{body}}};"


def header_text():
    lines = ["/* Generated by rtlsim/proto/gen_kat.py; do not edit. Research benchmark support. */",
             "#ifndef PROTO_KAT_H", "#define PROTO_KAT_H", "#include <stdint.h>"]
    for k, v in LABELS.items():
        lines.append(carray(k, v))
    lines.append(carray("KAT_SHA256_IN", SHA_IN))
    lines.append(carray("KAT_SHA256_OUT48", hashlib.sha256(SHA_IN).digest()[:6]))
    lines.append(carray("KAT_TAG_KEY", TAG_KEY))
    lines.append(carray("KAT_TAG_HEADER", TAG_HEADER))
    lines.append(carray("KAT_TAG_PAYLOAD", TAG_PAYLOAD))
    lines.append(carray("KAT_TAG_CRC", TAG_CRC))
    lines.append(f"#define KAT_TAG_LINK_ID {TAG_LINK_ID}")
    lines.append(f"#define KAT_TAG_TIMESTAMP 0x{TAG_TIMESTAMP:016x}ull")
    lines.append(carray("KAT_TAG_OUT", mavlink_tag(TAG_KEY, TAG_HEADER, TAG_PAYLOAD, TAG_CRC, TAG_LINK_ID,
                                                   TAG_TIMESTAMP)))
    lines.append(carray("KAT_KDF_SSX", KDF_SSX))
    lines.append(carray("KAT_KDF_SSKEM", KDF_SSKEM))
    lines.append(carray("KAT_KDF_TH", KDF_TH))
    lines.append(carray("KAT_KDF_OUT", kdf(KDF_SSX, KDF_SSKEM, KDF_TH)))
    lines.append("#endif")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    with open(sys.argv[1], "w") as fh:
        fh.write(header_text())
