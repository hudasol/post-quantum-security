/*
 * Round 6 protocol baselines on open RISC-V cores in RTL simulation (research benchmark code).
 * Author: Huda Mueen. SPDX-License-Identifier: Apache-2.0
 *
 * BENCHMARK CODE ONLY, NOT FOR USE. This file is protocol glue and timing code around pinned libraries:
 * Monocypher (X25519, Ed25519), mlkem-native (ML-KEM-768), mldsa-native (ML-DSA-44 and its SHAKE256) and
 * the MAVLink 2 C library (message signing and its SHA-256). It implements no cryptographic primitive.
 * Randomness comes from rtlsim/sw/bench_rng.c, a fixed seed test generator that is NOT a secure random
 * number generator; run r reseeds it with PROTO_SEED + r so that every run is repeatable. Secrets are not
 * wiped and nothing here is reviewed for side channels; the code exists only to count cycles.
 *
 * One image per design; exactly one PROTO_DESIGN_* macro is defined at compile time:
 *   PROTO_DESIGN_PRIMITIVES   each primitive timed alone
 *   PROTO_DESIGN_CLASSICAL    X25519 exchange, Ed25519 transcript signatures by both sides, key confirmation
 *   PROTO_DESIGN_PQ_ONLY      ML-KEM-768, ML-DSA-44 transcript signatures by both sides, key confirmation
 *   PROTO_DESIGN_HYBRID_F1    X25519 plus ML-KEM-768, ML-DSA-44 by both sides, key confirmation (design F1)
 *   PROTO_DESIGN_KEM_AUTH     X25519 plus ML-KEM-768, authentication by static ML-KEM-768 keys pinned at the
 *                             other side, no signatures, key confirmation (see the section of that design)
 *   PROTO_DESIGN_PER_COMMAND  ML-DSA-44 signature on each command (ground signs, vehicle verifies)
 *   PROTO_DESIGN_MAVLINK_TAG  MAVLink 2 signing tag per message (ground signs, vehicle checks)
 *
 * Session flights (formal/models/session_b_fixed.pv, docs/REFERENCE_ARCHITECTURE.md):
 *   F1 ground to vehicle: X25519 share gx (32 B) and ML-KEM-768 encapsulation key ek (1184 B)
 *   F2 vehicle to ground: X25519 share gy (32 B) and ML-KEM-768 ciphertext ct (1088 B)
 *   F3 ground to vehicle: signature of the ground over (3, idG, idV, th) and confirmation tag cG (16 B)
 *   F4 vehicle to ground: signature of the vehicle over (4, idV, idG, th) and confirmation tag cV (16 B)
 * with th = SHAKE256(label_th || F1 || F2, 32), k = SHAKE256(label_kdf || ss_x25519 || ss_kem || th, 32),
 * cG = SHAKE256(k || label_cg || th, 16), cV = SHAKE256(k || label_cv || th, 16), id = SHAKE256(label_id ||
 * long term public key, 32). The classical design has no ML-KEM parts and uses Ed25519; the post quantum
 * only design has no X25519 parts. The signatures cover the transcript hash, which covers the full
 * transcript. The labels and the expected values of the known answer tests come from kat.h, generated by
 * rtlsim/proto/gen_kat.py.
 */
