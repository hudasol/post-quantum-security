#if defined(SESSION)

#if USE_ED
#define SIG_BYTES 64
#define LT_PK 32
#define LT_SK 64
#else
#define SIG_BYTES DSA_SIG
#define LT_PK DSA_PK
#define LT_SK DSA_SK
#endif

#define F1_BYTES ((USE_X25519 ? 32 : 0) + (USE_KEM ? KEM_PK_OR0 : 0))
#define F2_BYTES ((USE_X25519 ? 32 : 0) + (USE_KEM ? KEM_CT_OR0 : 0))
#if USE_KEM
#define KEM_PK_OR0 KEM_PK
#define KEM_CT_OR0 KEM_CT
#else
#define KEM_PK_OR0 0
#define KEM_CT_OR0 0
#endif
#define F3_BYTES (SIG_BYTES + 16)
#define F4_BYTES (SIG_BYTES + 16)
#define KEM_OFF (USE_X25519 ? 32 : 0)

/* Long term keys (provisioned before the session, untimed). */
static uint8_t skG[LT_SK], pkG[LT_PK], skV[LT_SK], pkV[LT_PK];
static uint8_t idG[32], idV[32];
/* Messages as sent. */
static uint8_t F1[F1_BYTES], F2[F2_BYTES], F3[F3_BYTES], F4[F4_BYTES];
/* Ground state. */
static uint8_t g_x[32], g_th[32], g_k[32];
#if USE_KEM
static uint8_t g_dk[KEM_SK];
#endif
static int g_accept;
/* Vehicle state. */
static uint8_t v_y[32], v_th[32], v_k[32];
static int v_accept;

static void lt_keygen(uint8_t *sk, uint8_t *pk)
{
#if USE_ED
  uint8_t seed[32];
  randombytes(seed, 32);
  crypto_ed25519_key_pair(sk, pk, seed);
#else
  if (DSA_KEYPAIR(pk, sk) != 0)
  {
    pu_fails++;
  }
#endif
}

static int lt_sign(uint8_t *sig, const uint8_t *m, size_t mlen, const uint8_t *sk)
{
#if USE_ED
  crypto_ed25519_sign(sig, sk, m, mlen);
  return 0;
#else
  return DSA_SIGN(sig, m, mlen, dsa_ctx, 0, sk);
#endif
}

static int lt_verify(const uint8_t *sig, const uint8_t *m, size_t mlen, const uint8_t *pk)
{
#if USE_ED
  return crypto_ed25519_check(sig, pk, m, mlen);
#else
  return DSA_VERIFY(sig, m, mlen, dsa_ctx, 0, pk);
#endif
}

/* Ground: fresh X25519 share and fresh ML-KEM-768 key pair, build F1. */
__attribute__((noinline)) static int ground_f1(void)
{
  int rc = 0;
  g_accept = 0;
#if USE_X25519
  randombytes(g_x, 32);
  crypto_x25519_public_key(F1, g_x);
#endif
#if USE_KEM
  rc |= KEM_KEYPAIR(F1 + KEM_OFF, g_dk);
#endif
  return rc;
}

/* Vehicle: fresh X25519 share, X25519 secret, ML-KEM-768 encapsulation, transcript hash, session key;
 * build F2. */
__attribute__((noinline)) static int vehicle_f2(void)
{
  int rc = 0;
  uint8_t ssx[32], sskem[32];
  v_accept = 0;
#if USE_X25519
  randombytes(v_y, 32);
  crypto_x25519_public_key(F2, v_y);
  crypto_x25519(ssx, v_y, F1);
#endif
#if USE_KEM
  rc |= KEM_ENC(F2 + KEM_OFF, sskem, F1 + KEM_OFF);
#endif
  transcript_hash(v_th, F1, sizeof(F1), F2, sizeof(F2));
  kdf(v_k, USE_X25519 ? ssx : NULL, USE_KEM ? sskem : NULL, v_th);
  return rc;
}

/* Ground: X25519 secret, ML-KEM-768 decapsulation, transcript hash, session key, ground signature and
 * ground confirmation tag; build F3. */
__attribute__((noinline)) static int ground_f3(void)
{
  int rc = 0;
  uint8_t ssx[32], sskem[32], m[SIGN_INPUT_BYTES];
#if USE_X25519
  crypto_x25519(ssx, g_x, F2);
#endif
#if USE_KEM
  rc |= KEM_DEC(sskem, F2 + KEM_OFF, g_dk);
#endif
  transcript_hash(g_th, F1, sizeof(F1), F2, sizeof(F2));
  kdf(g_k, USE_X25519 ? ssx : NULL, USE_KEM ? sskem : NULL, g_th);
  sign_input(m, 3, idG, idV, g_th);
  rc |= lt_sign(F3, m, sizeof(m), skG);
  confirm_tag(F3 + SIG_BYTES, g_k, LABEL_CG, sizeof(LABEL_CG), g_th);
  return rc;
}

/* Vehicle: verify the ground signature against the pinned key, check the ground confirmation tag, sign
 * the transcript with the vehicle key, add the vehicle confirmation tag; build F4 and accept. */
__attribute__((noinline)) static int vehicle_f4(void)
{
  uint8_t m[SIGN_INPUT_BYTES], t[16];
  sign_input(m, 3, idG, idV, v_th);
  if (lt_verify(F3, m, sizeof(m), pkG) != 0)
  {
    return 1;
  }
  confirm_tag(t, v_k, LABEL_CG, sizeof(LABEL_CG), v_th);
  if (!eq16(t, F3 + SIG_BYTES))
  {
    return 2;
  }
  sign_input(m, 4, idV, idG, v_th);
  if (lt_sign(F4, m, sizeof(m), skV) != 0)
  {
    return 3;
  }
  confirm_tag(F4 + SIG_BYTES, v_k, LABEL_CV, sizeof(LABEL_CV), v_th);
  v_accept = 1;
  return 0;
}

/* Ground: verify the vehicle signature against the pinned key and check the vehicle confirmation tag;
 * accept. */
__attribute__((noinline)) static int ground_accept(void)
{
  uint8_t m[SIGN_INPUT_BYTES], t[16];
  sign_input(m, 4, idV, idG, g_th);
  if (lt_verify(F4, m, sizeof(m), pkV) != 0)
  {
    return 1;
  }
  confirm_tag(t, g_k, LABEL_CV, sizeof(LABEL_CV), g_th);
  if (!eq16(t, F4 + SIG_BYTES))
  {
    return 2;
  }
  g_accept = 1;
  return 0;
}

static void run_design(void)
{
  pu_msg(SET, "F1", "ground_to_vehicle", sizeof(F1));
  pu_msg(SET, "F2", "vehicle_to_ground", sizeof(F2));
  pu_msg(SET, "F3", "ground_to_vehicle", sizeof(F3));
  pu_msg(SET, "F4", "vehicle_to_ground", sizeof(F4));
  for (int r = 0; r < PROTO_RUNS; r++)
  {
    bench_rng_seed((uint64_t)PROTO_SEED + (uint64_t)r);
    /* Provisioning, untimed: long term key pairs and identities pinned at the other side. */
    lt_keygen(skG, pkG);
    lt_keygen(skV, pkV);
    hash_id(idG, pkG, sizeof(pkG));
    hash_id(idV, pkV, sizeof(pkV));

    PU_STEP(SET, "ground_f1", r, ground_f1());
    PU_STEP(SET, "vehicle_f2", r, vehicle_f2());
    PU_STEP(SET, "ground_f3", r, ground_f3());
    PU_STEP(SET, "vehicle_f4", r, vehicle_f4());
    PU_STEP(SET, "ground_accept", r, ground_accept());

    pu_chk(SET, "same_session_key", r, memcmp(g_k, v_k, 32) == 0);
    pu_chk(SET, "same_transcript_hash", r, memcmp(g_th, v_th, 32) == 0);
    pu_chk(SET, "vehicle_accepted", r, v_accept == 1);
    pu_chk(SET, "ground_accepted", r, g_accept == 1);
    if (r == 0)
    {
      /* Negative checks, untimed, first run only: a modified F3 signature, a modified F3 confirmation
       * tag and a modified F4 signature must each be rejected. */
      F3[5] ^= 1u;
      pu_chk(SET, "vehicle_rejects_modified_f3_signature", r, vehicle_f4() == 1);
      F3[5] ^= 1u;
      F3[SIG_BYTES] ^= 1u;
      pu_chk(SET, "vehicle_rejects_modified_f3_tag", r, vehicle_f4() == 2);
      F3[SIG_BYTES] ^= 1u;
      /* F4 was rebuilt by none of the failed calls above; modify its signature. */
      F4[7] ^= 1u;
      pu_chk(SET, "ground_rejects_modified_f4_signature", r, ground_accept() == 1);
      F4[7] ^= 1u;
    }
  }
}
#endif /* SESSION */

