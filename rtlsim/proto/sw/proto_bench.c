/* Hash based glue shared by the session designs and the primitives image.                        */

static void hash_id(uint8_t id[32], const uint8_t *pk, size_t pklen)
{
  ph_ctx c;
  ph_init(&c);
  ph_absorb(&c, LABEL_ID, sizeof(LABEL_ID));
  ph_absorb(&c, pk, pklen);
  ph_squeeze(&c, id, 32);
}

static void transcript_hash(uint8_t th[32], const uint8_t *f1, size_t f1len, const uint8_t *f2,
                            size_t f2len)
{
  ph_ctx c;
  ph_init(&c);
  ph_absorb(&c, LABEL_TH, sizeof(LABEL_TH));
  ph_absorb(&c, f1, f1len);
  ph_absorb(&c, f2, f2len);
  ph_squeeze(&c, th, 32);
}

/* ssx or sskem may be NULL when the design has no such component. */
static void kdf(uint8_t k[32], const uint8_t *ssx, const uint8_t *sskem, const uint8_t th[32])
{
  ph_ctx c;
  ph_init(&c);
  ph_absorb(&c, LABEL_KDF, sizeof(LABEL_KDF));
  if (ssx)
  {
    ph_absorb(&c, ssx, 32);
  }
  if (sskem)
  {
    ph_absorb(&c, sskem, 32);
  }
  ph_absorb(&c, th, 32);
  ph_squeeze(&c, k, 32);
}

static void confirm_tag(uint8_t tag[16], const uint8_t k[32], const uint8_t *label, size_t llen,
                        const uint8_t th[32])
{
  ph_ctx c;
  ph_init(&c);
  ph_absorb(&c, k, 32);
  ph_absorb(&c, label, llen);
  ph_absorb(&c, th, 32);
  ph_squeeze(&c, tag, 16);
}

static void sign_input(uint8_t m[SIGN_INPUT_BYTES], uint8_t flight, const uint8_t ida[32],
                       const uint8_t idb[32], const uint8_t th[32])
{
  m[0] = flight;
  memcpy(m + 1, ida, 32);
  memcpy(m + 33, idb, 32);
  memcpy(m + 65, th, 32);
}
