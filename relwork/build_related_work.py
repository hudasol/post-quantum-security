#!/usr/bin/env python3
"""Write docs/RELATED_WORK.md from data/raw/S14_related_work.csv (round 6, limitation L5).

Every cell of the comparison table is read from the CSV; the counts in the prose are computed
from it. Values are copied as the sources state them, with their location; a row read only
through the summarising fetch tool, or only from an abstract, is marked as not usable as
evidence (round 5 inclusion 4 and deviation 3). The row for this study names its design and
methods only; its numbers are in the round 6 result documents, measured under other conditions.
Rerun: python3 relwork/build_related_work.py   (add --check to fail when the file is stale)
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "data" / "raw" / "S14_related_work.csv"
OUT = ROOT / "docs" / "RELATED_WORK.md"

THIS_STUDY = {
    "work": "This study (round 6)",
    "design": "hybrid session: X25519 plus ML-KEM-768 key establishment, ML-DSA-44 transcript signatures by both sides "
              "(design change F1) and key confirmation, then a symmetric tag per command; LMS signed firmware with a signed "
              "version and a monotonic counter",
    "platform": "Ibex and CV32E40P open RISC-V cores in cycle accurate RTL simulation; Cortex-M boards prepared, not measured",
    "link": "SiK class telemetry link emulated in software in the loop; IEEE 802.15.4 and LoRa in ns-3",
    "measured": "RTL simulated, SITL measured, emulated and modelled, each labelled",
    "handshake": "executed in round 6 with one code base on two open RISC-V core designs (RTL simulated, docs/RTL_BASELINES.md) and over an emulated SiK radio with ArduPilot in the loop (docs/SITL_STUDY_R6.md)",
    "per_message": "tag per message and signature per command executed in round 6 (same documents)",
    "availability": "SITL measured with ArduPilot under the published, strict next sequence and replay cache rules on paired seeds, and modelled per rule (docs/SITL_STUDY_R6.md, docs/MISSION_STUDY.md)",
    "formal": "ProVerif models of the stated and changed designs and of replay rules (docs/FORMAL_VERIFICATION.md, sections 5 and 9)",
}


def rows():
    with open(SRC, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def cell(x):
    return str(x).replace("|", "/").replace("\n", " ").strip()


def short(r):
    authors = r["citation"].split(". ", 1)[0]
    if authors.lower().startswith("forum post"):
        return f"{r['id']} forum post ({r['year']})"
    first = authors.split(",")[0].strip()
    more = " et al." if "," in authors else ""
    return f"{r['id']} {first}{more} ({r['year']})"


def with_loc(value, loc):
    value, loc = cell(value), cell(loc)
    return f"{value} [{loc}]" if value and loc else value


def handshake(r):
    if r["handshake_value_as_stated"]:
        return with_loc(r["handshake_value_as_stated"], r["handshake_location"])
    return cell(r["handshake_reported"])


def per_message(r):
    if r["per_message_value_as_stated"]:
        return with_loc(r["per_message_value_as_stated"], r["per_message_location"])
    if r["other_value_as_stated"] and r["per_message_reported"].startswith("not applicable"):
        return cell(r["per_message_reported"]) + "; " + with_loc(r["other_value_as_stated"], r["other_location"])
    return cell(r["per_message_reported"])


def ids(rs, pred):
    return [r["id"] for r in rs if pred(r)]


def fmt(lst):
    return ", ".join(lst) if lst else "none"


def render():
    rs = rows()
    direct = ids(rs, lambda r: r["full_text_read"] == "yes")
    fetched = ids(rs, lambda r: r["full_text_read"].startswith("yes, through"))
    partial = ids(rs, lambda r: r["full_text_read"] in ("no", "partly"))
    usable = ids(rs, lambda r: r["usable_as_evidence"] == "yes")
    hw_handshake = ids(rs, lambda r: r["handshake_reported"] == "yes" and "measured on hardware" in r["measured_how"])
    emu_handshake = ids(rs, lambda r: r["handshake_reported"] == "yes" and "emulated" in r["measured_how"])
    est_handshake = ids(rs, lambda r: r["handshake_reported"].startswith("yes") and "estimated" in r["measured_how"])
    machine_formal = ids(rs, lambda r: "Tamarin" in r["formal_check"] and "no ProVerif or Tamarin" not in r["formal_check"])
    availability = ids(rs, lambda r: r["availability_reported"] and not r["availability_reported"].startswith(("no", "not")))
    drone = ids(rs, lambda r: any(w in (r["citation"] + " " + r["design"]).lower() for w in ("uav", "drone", "unmanned", "mavlink")))

    out = ["# Related work: prior designs and their reported costs", "",
           "Author: Huda Mueen. Generated by `relwork/build_related_work.py` from `data/raw/S14_related_work.csv`; do not edit by hand.", "",
           "## Scope and reading rule", "",
           "Round 6 collected published designs and measurements of post quantum and classical authentication and key exchange "
           "for drones, UAVs, MAVLink, ROS 2 and DDS, robots and other constrained wireless links, and of post quantum secure "
           "boot and update on embedded processors. Searches used the web search and fetch tools of the working environment; "
           "refused fetches are recorded in the CSV and in `data/raw/S14_dblp_log.csv`, not worked around.", "",
           f"Works retrieved: {len(rs)}. Full text read directly from a copy the author supplied (the same file as the URL): {len(direct)} ({fmt(direct)}). "
           f"Full text read only through the summarising fetch tool: {len(fetched)}. Abstract only, partly read or not retrieved: "
           f"{len(partial)} ({fmt(partial)}).", "",
           "Values are copied as each source states them, with the table or section in brackets. Under the round 5 rules "
           "(inclusion 4 and deviation 3) a value read only through the summarising fetch tool or only from an abstract is "
           f"not usable as evidence until it is read directly; the rows usable as evidence are {fmt(usable)}. None of these values "
           "enters `data/evidence.csv` in this round.", "",
           "## Comparison of designs", "",
           "| work | design | platform | link | measured how | handshake cost | per message cost | availability | formal check |",
           "|---|---|---|---|---|---|---|---|---|"]
    t = THIS_STUDY
    out.append("| " + " | ".join(cell(x) for x in (t["work"], t["design"], t["platform"], t["link"], t["measured"], t["handshake"],
                                                 t["per_message"], t["availability"], t["formal"])) + " |")
    for r in rs:
        out.append("| " + " | ".join([cell(short(r)), cell(r["design"]), cell(r["platform_core"]), cell(r["link"]), cell(r["measured_how"]),
                                      handshake(r), per_message(r), cell(r["availability_reported"]), cell(r["formal_check"])]) + " |")
    out += ["", "## What is new here, and what is not", "",
            f"Among the {len(rs)} works retrieved, {len(drone)} address drones, UAVs, unmanned systems or MAVLink directly "
            f"({fmt(drone)}). A post quantum handshake measured on embedded hardware is reported by {fmt(hw_handshake)}; over an "
            f"emulated link from a host by {fmt(emu_handshake)}; and as an estimate composed from per operation costs by "
            f"{fmt(est_handshake)}. A machine checked symbolic model of the design is reported by {fmt(machine_formal)}. "
            f"Availability of a message stream under loss is reported by {fmt(availability)}, for vehicle to vehicle "
            "broadcast rather than a command channel.", "",
            "Against this retrieved set, what this study adds is the combination, not any single part: one code base that executes the command channel "
            "baselines, from no authentication to a post quantum signature per command, on the Ibex and CV32E40P cores at cycle "
            "level and with ArduPilot in the loop; the same designs checked in ProVerif, including a replay cache rule; and command "
            "availability measured and modelled under the published, strict next sequence and replay cache rules on a telemetry class link. Each part has "
            "precedents above: embedded handshake measurements, emulated UAV link handshakes and Tamarin models of a UAV key "
            "exchange.", "",
            "Limits of this comparison. The values above were measured by others on other processors, libraries, links and "
            "settings, so the table compares designs and methods, not numbers. Cycle accurate simulation of open cores is not a "
            "measurement on a Cortex-M board or over a radio, which this study still lacks. The retrieved set is not exhaustive: "
            "the dblp index could only be reached through search engine results (`docs/SEARCH_PROTOCOL.md`, round 6 section), "
            "several full texts were refused, and works not found by the searches may exist.", ""]
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if old != text:
            sys.exit("docs/RELATED_WORK.md is stale: run python3 relwork/build_related_work.py")
        print("docs/RELATED_WORK.md current")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} from {len(rows())} works")


if __name__ == "__main__":
    main()
