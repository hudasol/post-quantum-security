"""Second round link study: sweeps, Monte Carlo grid, low rate profiles and
validation. Author: Huda Mueen.

Run from the repository root:  python -m linksim.study
Writes linksim/results/*.csv (each with its configuration and seeds) and
docs/LINKSIM_STUDY.md. All results are estimated from published sizes, not
measured.
"""
import argparse
import csv
import os
import platform
import time

from . import lowrate, model, montecarlo as mc, validate

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "linksim", "results")
DOC = os.path.join(ROOT, "docs", "LINKSIM_STUDY.md")
LOSSES = (0.0, 0.01, 0.05, 0.10, 0.20)
LABEL = "estimated"

SWEEPS = {
    "payload": {"sik": (64, 128, 239), "lorawan": (11, 25, 51),
                "ieee802154": (40, 81, 100), "ble": (23, 100, 244),
                "generic10k": (64, 128, 239)},
    "rate_scale": (0.5, 0.75, 1.0, 1.5, 2.0),
    "loss": (0.0, 0.01, 0.02, 0.05, 0.10, 0.20),
    "max_retries": (1, 3, 5, 10, 20),
    "rto_factor": (1.5, 2.0, 3.0, 4.0),
}
SWEEP_LINKS = ("sik", "lorawan", "ieee802154", "ble", "generic10k")


def _write(name, rows, fields):
    os.makedirs(RES, exist_ok=True)
    with open(os.path.join(RES, name), "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, lineterminator="\n")
        w.writeheader()
        for r in rows:
            w.writerow({k: _fmt(r.get(k, "")) for k in fields})


def _fmt(v):
    if isinstance(v, float):
        return "%.6g" % v
    return v


STAT_FIELDS = ["trials", "completed", "completion", "completion_lo",
               "completion_hi", "mean", "ci_lo", "ci_hi", "median", "p05",
               "p95", "sd", "base_seed", "deterministic"]


def run_grid(p, trials):
    rows = []
    links = model.build_links(p)
    for k in model.LINK_ORDER:
        for variant in ("hybrid", "hybrid_prov"):
            flights = model.handshake_flights(p, variant)
            for proto in ("sw", "sr"):
                for loss in LOSSES:
                    r = mc.mc_cell(links[k], flights, proto, loss, p, trials)
                    r.update({"link": k, "variant": variant, "proto": proto,
                              "loss": loss, "max_retries": p["max_retries"]})
                    rows.append(r)
    # Q2.5: short retry limit cell
    q = dict(p)
    q["max_retries"] = 3
    r = mc.mc_cell(links["ble"], model.handshake_flights(q, "hybrid"), "sw",
                   0.20, q, trials)
    r.update({"link": "ble", "variant": "hybrid", "proto": "sw",
              "loss": 0.20, "max_retries": 3})
    rows.append(r)
    return rows


def run_sweeps(p, trials):
    rows = []
    for k in SWEEP_LINKS:
        for axis, vals in SWEEPS.items():
            if axis == "payload":
                vals = vals[k]
            for loss in (0.0, 0.05):
                if axis == "loss" and loss:
                    continue
                for v, r in mc.sweep(k, axis, vals, p, "sr", loss, "hybrid",
                                     trials):
                    r.update({"link": k, "axis": axis, "value": v,
                              "loss": v if axis == "loss" else loss})
                    rows.append(r)
    return rows


def write_config(p, trials, seconds):
    rows = [
        {"key": "label", "value": LABEL},
        {"key": "trials_per_cell", "value": trials},
        {"key": "seeds", "value": "%d to %d (seed of trial i is %d + i)" % (
            mc.BASE_SEED, mc.BASE_SEED + trials - 1, mc.BASE_SEED)},
        {"key": "zero_loss_cells", "value": "deterministic; one run stands for all trials"},
        {"key": "interval", "value": "mean plus or minus 1.96 sd / sqrt(n); completion by Wilson score"},
        {"key": "loss_model", "value": "independent Bernoulli per frame, data and acknowledgements"},
        {"key": "python", "value": platform.python_version()},
        {"key": "run_seconds", "value": "%.1f" % seconds},
    ]
    for r in model.load_param_rows():
        rows.append({"key": "param." + r["name"], "value": r["value"]})
    _write("config.csv", rows, ["key", "value"])


def model_fmt(s):
    if s == "" or s is None:
        return "n/a"
    s = float(s)
    if s != s:
        return "n/a"
    if s < 1:
        return "%.0f ms" % (s * 1000)
    if s < 120:
        return "%.2f s" % s
    if s < 7200:
        return "%.1f min" % (s / 60)
    return "%.2f h" % (s / 3600)


def write_doc(grid, sweeps, low, val, trials):
    L = []
    a = L.append
    a("# Link study, second round")
    a("")
    a("Author: Huda Mueen. Generated by `python -m linksim.study`; do not edit by hand. "
      "Label: **estimated** (from published sizes, not measured). Every Monte Carlo cell "
      "with loss uses %d trials with seeds %d to %d (zero loss cells are deterministic "
      "single runs); configuration and every parameter are in "
      "`linksim/results/config.csv`. Raw results: `linksim/results/`." % (
          trials, mc.BASE_SEED, mc.BASE_SEED + trials - 1))
    a("")
    a("## 1. Monte Carlo grid: hybrid handshake, public key sent")
    a("")
    a("Median wall time, with the 95 percent interval of the mean and the completion "
      "rate. Retry limit 20 unless stated.")
    a("")
    a("| link | protocol | loss | median | mean (95% interval) | p95 | completed |")
    a("|---|---|---|---|---|---|---|")
    for r in grid:
        if r["variant"] != "hybrid" or r["max_retries"] != 20.0:
            continue
        a("| %s | %s | %g%% | %s | %s (%s to %s) | %s | %.1f%% |" % (
            r["link"], r["proto"], 100 * r["loss"], model_fmt(r["median"]),
            model_fmt(r["mean"]), model_fmt(r["ci_lo"]), model_fmt(r["ci_hi"]),
            model_fmt(r["p95"]), 100 * r["completion"]))
    short = [r for r in grid if r["max_retries"] == 3][0]
    a("")
    a("Short retry limit (BLE, stop and wait, retry limit 3, 20 percent loss): "
      "%.1f%% of handshakes complete (Wilson 95%% interval %.1f%% to %.1f%%)." % (
          100 * short["completion"], 100 * short["completion_lo"],
          100 * short["completion_hi"]))
    a("")
    a("## 2. One at a time sweeps (selective repeat, hybrid, key sent)")
    a("")
    a("Relative change of mean wall time against the base value of each axis "
      "(payload: the link's cited fragment payload; rate scale 1; retry limit 20; "
      "timeout factor 2).")
    a("")
    a("| link | axis | loss | values | relative change of mean |")
    a("|---|---|---|---|---|")
    base_of = {"rate_scale": 1.0, "max_retries": 20, "rto_factor": 2.0,
               "loss": 0.0}
    p = model.load_params()
    links = model.build_links(p)
    for k in SWEEP_LINKS:
        for axis in SWEEPS:
            for loss in (0.0, 0.05):
                sel = [r for r in sweeps if r["link"] == k and r["axis"] == axis
                       and (axis == "loss" or r["loss"] == loss)]
                if axis == "loss" and loss:
                    continue
                if not sel:
                    continue
                b = links[k].cap if axis == "payload" else base_of[axis]
                base = [r for r in sel if r["value"] == b]
                if not base or base[0]["mean"] != base[0]["mean"]:
                    continue
                bm = base[0]["mean"]
                ch = ", ".join("%g: %+.1f%%" % (r["value"], 100 * (r["mean"] / bm - 1))
                               if r["mean"] == r["mean"] else "%g: none complete" % r["value"]
                               for r in sel)
                a("| %s | %s | %s | %s | %s |" % (
                    k, axis, "swept" if axis == "loss" else "%g%%" % (100 * loss),
                    " ".join("%g" % r["value"] for r in sel), ch))
    a("")
    a("## 3. Lowest rate radio profiles")
    a("")
    a("Fragments and the no loss lower bound on wall time (flights back to back under "
      "a 1 percent duty cycle, no acknowledgements). Fragment header and MAC overhead "
      "are ASSUMPTIONS swept here. US915 DR0 has no cited bit rate, so only fragments.")
    a("")
    a("| profile | variant | fragment header B | MAC overhead B | fragments | lower bound |")
    a("|---|---|---|---|---|---|")
    for r in low:
        a("| %s | %s | %d | %d | %d | %s |" % (
            r["label"], r["variant"], r["frag_hdr_bytes"], r["mac_overhead_bytes"],
            r["fragments"], model_fmt(r["floor_wall_s"])))
    a("")
    a("## 4. Validation against a published link figure")
    a("")
    a("Target: Table 5 of ePrint 2026/2343, TLS 1.3 handshake over an emulated UAV "
      "profile (57.6 kbps, 40 ms delay), rows S10F-131 to S10F-150 of "
      "`data/evidence.csv`. Model: published clear link time plus 2 round trips of "
      "2 x 40 ms plus bytes over rate; variant `tcp` adds 52 B per 1448 B segment "
      "(both ASSUMPTIONS). Error = predicted / published minus 1. This table "
      "deliberately sets published values (labelled published, with row ids) beside "
      "estimated ones (labelled predicted) because its purpose is to measure the "
      "model's error. Other comparisons across labels in this repository also carry a "
      "label per column.")
    a("")
    a("| group | bytes rd/wr | published UAV ms | predicted ms | error | predicted with TCP ms | error | published minus P-256 ms | predicted minus P-256 ms | error of difference |")
    a("|---|---|---|---|---|---|---|---|---|---|")
    for r in val:
        de = r.get("diff_err_plain", float("nan"))
        a("| %s | %d/%d | %.0f | %.0f | %+.1f%% | %.0f | %+.1f%% | %.0f | %.0f | %s |" % (
            r["group"], r["rd"], r["wr"], r["uav_ms"], r["pred_plain"],
            100 * r["err_plain"], r["pred_tcp"], 100 * r["err_tcp"],
            r.get("meas_diff", float("nan")), r.get("pred_diff_plain", float("nan")),
            "n/a" if de != de else "%+.1f%%" % (100 * de)))
    errs = [abs(r["err_plain"]) for r in val]
    if errs:
        a("")
        a("Mean absolute error of the absolute times: %.1f%% (plain), %.1f%% (with TCP "
          "headers), over %d groups." % (100 * sum(errs) / len(errs),
                                         100 * sum(abs(r["err_tcp"]) for r in val) / len(val),
                                         len(val)))
    a("")
    a("Limits: the paper does not say whether netem delayed one or both directions, "
      "the TLS stack and TCP behaviour (slow start, acknowledgements) are not modelled, "
      "and the clear link time stands for all fixed costs. The check validates the "
      "bytes over rate part of the model on one bandwidth bound link; it does not "
      "validate the duty cycle, fragmentation or loss parts, for which no published "
      "figure is in the evidence table.")
    a("")
    a("_" + model.FOOTER + "_")
    with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--trials", type=int, default=mc.TRIALS)
    a = ap.parse_args(argv)
    t0 = time.time()
    p = model.load_params()
    print("label=%s trials=%d seeds=%d..%d" % (LABEL, a.trials, mc.BASE_SEED,
                                               mc.BASE_SEED + a.trials - 1))
    grid = run_grid(p, a.trials)
    _write("mc_grid.csv", grid, ["link", "variant", "proto", "loss",
                                 "max_retries"] + STAT_FIELDS)
    sweeps = run_sweeps(p, a.trials)
    _write("sweeps.csv", sweeps, ["link", "axis", "value", "loss"] + STAT_FIELDS)
    low = lowrate.table(p)
    _write("lowrate.csv", low, ["profile", "label", "variant", "frag_hdr_bytes",
                                "mac_overhead_bytes", "fragments", "floor_wall_s"])
    val = validate.run(p)
    _write("validation.csv", val, ["group", "ids", "rd", "wr", "clear_ms", "uav_ms",
                                   "pred_plain", "err_plain", "pred_tcp", "err_tcp",
                                   "meas_diff", "pred_diff_plain", "diff_err_plain",
                                   "pred_diff_tcp", "diff_err_tcp"])
    write_config(p, a.trials, time.time() - t0)
    write_doc(grid, sweeps, low, val, a.trials)
    print("wrote linksim/results/ and docs/LINKSIM_STUDY.md in %.1f s" % (time.time() - t0))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
