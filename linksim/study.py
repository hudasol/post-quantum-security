    from . import validate_v4 as v4
    p = model.load_params()
    val, diag, cf = v4.validation(p), v4.diagnosis(p), v4.closed_form_rows(p)
    applied = [r for r in diag if r["applied"] in ("baseline", "yes")]
    last = applied[-1]
    lora_rows = [r for r in val if r["figure"].startswith("LoRa") and "time on air formula" in r["model"]]
    old_lora = [r for r in val if r["figure"].startswith("LoRa") and "third round" in r["model"]][0]
    a("### 4.4 Round 4 validation (fourth round, 2026-10-20)")
    a("")
    a("Generated through `linksim/validate_v4.py` (seed %d). Sources: `data/raw/S12_link_sources.md` and "
      "`data/evidence.csv`. Full tables: `linksim/results/validation_v4.md`, `validation_v4.csv`, "
      "`diagnosis_v4.csv`, `closed_form_v4.csv`; figure `linksim/results/fig_diagnosis_v4.svg`. "
      "Published values are labelled published and model values modelled in every column." % v4.SEED)
    a("")
    a("IEEE 802.15.4 gap, one cited cause at a time (cumulative; 50 kB, no loss; cross check against the prose "
      "range of 30 to 60 s, never used to calibrate):")
    a("")
    a("| step | cause | applied | time after s (modelled) | error vs 30 s (modelled vs published) | source |")
    a("|---|---|---|---|---|---|")
    for r in diag:
        a("| %s | %s | %s | %.2f | %+.1f%% | %s |" % (r["step"], r["cause"], r["applied"], r["time_s_modelled_after"],
                                                  r["err_low_pct_after"], r["source"]))
