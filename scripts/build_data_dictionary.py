#!/usr/bin/env python3
"""Write docs/DATA_DICTIONARY.md: what each column of the main data files means.

The evidence table columns are described below by hand (they are the protocol schema). For every
committed CSV in the result folders, the columns, their type and one example value are listed
automatically, so the dictionary follows the files.
"""
import csv
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE_COLS = {
    "id": "row id; the prefix names the stream that added the row (S2, S3, S7, S8, S10, S12, S13)",
    "scheme": "algorithm family as named by the source (for example ML-KEM, ML-DSA, LMS)",
    "parameter_set": "parameter set as named by the source; pre standard names are kept",
    "operation": "operation as named by the source (keygen, encaps, decaps, sign, verify, or a longer phrase)",
    "device": "board or chip as named by the source",
    "core": "processor core as named by the source",
    "clock_mhz": "clock frequency during the measurement, if stated",
    "library": "implementation or library as named by the source",
    "library_version": "version, tag or commit if stated",
    "compiler_flags_or_notes": "compiler, flags, statistic and other measurement notes from the source",
    "cycles": "cycle count as published (no conversion except stated unit factors)",
    "ram_bytes": "RAM figure as published (definition varies; see the warning)",
    "stack_bytes": "stack figure as published (definition varies; see the warning)",
    "flash_or_code_bytes": "code or flash size as published",
    "energy_uj": "energy per operation in microjoules as published",
    "key_or_sig_size_bytes": "key, ciphertext or signature size in bytes",
    "size_kind": "which object the size refers to",
    "evidence_type": "published, or derived-from-published for arithmetic on published values",
    "source_title": "title of the source",
    "source_url": "URL of the source as retrieved",
    "retrieval_date": "date the source was read",
    "location_in_source": "page, table, row and column of the value",
    "comparability_warning": "what limits comparison with other rows",
    "stream": "derived: the staging stream that added the row",
    "scheme_family": "derived: family by string rule (merge script)",
    "standard_status": "derived: standard, draft or pre standard by string rule",
    "device_class": "derived: mcu, host-cpu, fpga-asic-soft-core, no-device or standard-size",
}
RESULT_DIRS = ["cyclemodel/results", "rtlsim/results", "energy/results", "bootchain/results", "mission/results",
               "linksim/results", "planner/results", "bench/board_kit/results", "data/meta", "data/verify5"]
EXTRA = ["data/reference_profiles.csv", "data/policy_timeline.csv", "data/claims_register.csv", "data/context_entities.csv"]


def kind(values):
    vals = [v for v in values if v.strip()]
    if not vals:
        return "empty"
    try:
        [float(v.replace(",", "")) for v in vals]
        return "number"
    except ValueError:
        return "text"


def describe(path):
    with open(ROOT / path, newline="", encoding="utf-8") as fh:
        rd = csv.reader(fh)
        header = next(rd, [])
        rows = [r for _, r in zip(range(200), rd)]
    out = [f"### `{path}`", "", f"{len(header)} columns.", "", "| column | type | example |", "|---|---|---|"]
    for i, c in enumerate(header):
        col = [r[i] for r in rows if i < len(r)]
        ex = next((v for v in col if v.strip()), "")
        ex = (ex[:60] + "...") if len(ex) > 60 else ex
        out.append(f"| {c} | {kind(col)} | {ex.replace('|', '/')} |")
    return out + [""]


def main():
    tracked = set(subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split("\n"))
    lines = ["# Data dictionary", "", "Author: Huda Mueen. Generated by `scripts/build_data_dictionary.py`; do not edit by hand.", "",
             "Labels used across the repository: published, host measured, emulated, estimated, modelled (with its validation error), "
             "RTL simulated (open source core design, not Arm silicon), planned; board measured is reserved. "
             "Derived from published means arithmetic on published values; assumption marks a parameter set by the author with a stated range; "
             "synthetic marks invented fleets or counts.", "", "## data/evidence.csv", "", "| column | meaning |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in EVIDENCE_COLS.items()]
    lines += ["", "## Result files", ""]
    files = sorted(t for t in tracked if t.endswith(".csv") and any(t.startswith(d + "/") for d in RESULT_DIRS)) + [t for t in EXTRA if t in tracked]
    for f in files:
        lines += describe(f)
    (ROOT / "docs" / "DATA_DICTIONARY.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"described {len(files)} result files")


if __name__ == "__main__":
    main()
