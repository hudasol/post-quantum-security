"""Texts of the round 4 robotics proposal and its three short variants. Author: Huda Mueen.

Every number goes through the `claim` function passed in by scripts/build_paper.py, so it is read
from a result file and recorded in data/claims_register.csv. Entity facts are cited by their id in
data/context_entities.csv; nothing else about any organisation is stated.
"""

SEED_NOTE = ("This is a student research proposal and a seed for discussion. It is not a deployment, it has no "
             "relationship with or endorsement by any organisation named, and organisation facts come only from the "
             "public pages listed in `docs/CONTEXT_ENTITIES.md`.")


def numbers(claim, doc):
    es = "cyclemodel/results/error_summary.csv"
    mb = "mission/results/base.csv"
    dg = "linksim/results/diagnosis_v4.csv"
    pm = "planner/results/profile_mc_summary.csv"
    vt = "bootchain/results/verify_time.csv"
    qm = 'vehicle == "{v}" and arch == "{a}" and link == "{l}"'
    qb = 'target == "Crazyflie 2.1 (STM32F405)" and image_bytes == 1000000 and scheme == "LMS" and hash == "{h}"'
    p = doc.replace("docs/", "").replace(".md", "").lower()
    c = lambda cid, *a, **k: claim(f"{p}_{cid}", *a, doc=doc, **k)
    return {
        "rows": c("rows", "data/evidence.csv", "id", aggregate="count", label="published"),
        "cm_med": c("cm_med", es, "median_abs_pct", 'model == "fitted" and subset == "test, all"', fmt="{:.1f}", label="modelled"),
        "cm_sign": c("cm_sign", es, "worst_abs_pct", 'model == "fitted" and subset == "test, all"', fmt="{:.0f}", label="modelled"),
        "m_b": c("m_b", mb, "avail_mean", qm.format(v="drone", a="B", l="sik"), fmt="{:.3f}", label="estimated"),
        "m_c": c("m_c", mb, "avail_mean", qm.format(v="drone", a="C", l="sik"), fmt="{:.3f}", label="estimated"),
        "m_c_lat": c("m_c_lat", mb, "added_latency_ms_median", qm.format(v="drone", a="C", l="sik"), fmt="{:.0f}", label="estimated"),
        "d_factor": c("d_factor", dg, "factor_below_low_after", 'step == "6"', fmt="{:.1f}", label="modelled"),
        "prof_med": c("prof_med", pm, "median", 'fleet == "profile" and thresholds == "uncertain"', fmt="{:.2f}", label="estimated"),
        "boot_sw": c("boot_sw", vt, "total_ms_estimated", qb.format(h="software SHA-256"), fmt="{:.0f}", label="estimated"),
        "boot_hw": c("boot_hw", vt, "total_ms_estimated", qb.format(h="hardware HASH"), fmt="{:.0f}", label="estimated"),
    }


def robotics(claim):
    doc = "docs/PROPOSAL_ROBOTICS.md"
    n = numbers(claim, doc)
    text = f"""# Proposal: a post quantum ready command and update channel for drones and ground robots, from model to hardware in the loop

Author: Huda Mueen. Generated by `scripts/build_paper.py` from `scripts/proposal_texts.py`; every number below is read from a result file and checked by `scripts/check_numbers.py`.

{SEED_NOTE}

## 1. Problem

Unmanned aircraft and ground robots accept commands and firmware over narrow radio links, authenticated today with classical public key cryptography on microcontroller flight computers. The post quantum replacements are standardised, and some buyers have set dates (`docs/POLICY_TIMELINE.md`). An operator still cannot answer three practical questions from evidence: will the new algorithms fit and run fast enough on the flight controller it has; will the link carry the larger messages without hurting control; and which of its devices must be replaced rather than updated.

## 2. What the evidence already shows (this repository)

1. A provenance controlled table of {n['rows']} published rows, every new row read by two independent readers (`docs/VERIFICATION5.md`).
2. A trace driven cycle model that predicts published Cortex-M4 cycle counts on held out rows of the same code base with a median error of {n['cm_med']} percent (modelled; interpolation within one code base, not transfer; signing misses by up to {n['cm_sign']} percent), with predictions for a board session registered in advance (`docs/PREDICTIONS_V4_BOARD.md`).
3. A mission simulation in which a hybrid session keeps a drone's command availability on a telemetry radio at a mean of {n['m_b']} (estimated), as without authentication, while a post quantum signature on every command lowers it to {n['m_c']} and adds about {n['m_c_lat']} ms per command (`docs/MISSION_STUDY.md`).
4. A boot model in which verifying a 1 MB image with LMS takes about {n['boot_sw']} ms with a software hash and {n['boot_hw']} ms with hash hardware on a 168 MHz Cortex-M4 (estimated; `docs/BOOT_UPDATE_STUDY.md`).
5. A fleet study on real board classes with a median of {n['prof_med']} of devices needing replacement under stated assumptions (estimated; `docs/PLANNER_STUDY.md`).
6. The main known gap: on IEEE 802.15.4 the link model is still {n['d_factor']} times faster than a published transfer time (`docs/LINKSIM_STUDY.md`).

## 3. Aim and hypotheses

Aim: test the models of this repository against measurements, and turn them into a measured, reusable reference design for an authenticated command and update channel on a real flight controller, and publish the measurements with their provenance.

| ID | Hypothesis | Refuted if |
|---|---|---|
| H1 | Board measured cycles fall inside the registered intervals for at least four fifths of the 18 harness operations in `docs/PREDICTIONS_V4_BOARD.md`, without a shared sign of error (stricter than the registered rule of one third; `docs/PREDICTIONS_V4_BOARD_NOTES.md`) | more than a fifth fall outside, or more than four fifths of the errors share one sign |
| H2 | On a real telemetry radio pair, a hybrid session handshake completes within 2 s at the radio's default settings | the median handshake exceeds 2 s |
| H3 | With a session design, the added latency per command stays within the control deadline of the flight stack's command stream | any documented command stream misses its deadline more often than without authentication |
| H4 | Free flash and RAM after the flight stack, read from real build output, leave room for an LMS verifier and an ML-KEM session on current flight controllers | a current board class has less free memory than the published footprint of either |

## 4. Work plan (six to twelve months, part time)

| Phase | Months | Milestone | Decision gate |
|---|---|---|---|
| 1 | 1 | Borrowed Cortex-M4F board: run `bench/board_kit/`, score `docs/PREDICTIONS_V4_BOARD.md` | if H1 fails, refit the cycle model on the board data before any further claim |
| 2 | 2 to 3 | Software in the loop: an autopilot simulation with a session layer in front of the command stream, using existing libraries as benchmark subjects | if added latency exceeds the deadline, stop and redesign the session layer |
| 3 | 3 to 5 | Hardware in the loop: the board from phase 1 with a borrowed telemetry radio pair; measure handshake, rekey and update transfer | if H2 fails, model the radio's MAC behaviour from measurements |
| 4 | 5 to 7 | Free memory from real flight stack builds for the board classes in `data/reference_profiles.csv`; rerun the fleet study | replaces the assumed free share |
| 5 | 7 to 12 | Reference design note, dataset release with provenance, paper | supervisor review |

## 5. Deliverables

A board measured table (labelled separately from published values), a measured link timing dataset, a session layer design note with its threat model, an updated fleet study, and a paper. Code and data stay with the author until a licence is agreed.

## 6. Evaluation

Each phase reports against its hypothesis with the refutation rule above, intervals, and the raw files. Predictions are hashed before each experiment, as in this repository.

## 7. Risks

| Risk | Mitigation |
|---|---|
| No board or radio can be borrowed | emulator and open core simulation continue; the board session is short by design (`bench/board_kit/CHECKLIST.md`) |
| Flight stack build output is not shareable | use open source flight stacks whose builds are public |
| The cycle model fails on the board | that is a result: refit and report both |
| Scope creep into implementing cryptography | the project only integrates and measures existing, pinned libraries |

## 8. Ethics and safety

Defensive work only: no attack code and no side channel guidance. Flights, if any, follow the host lab's safety rules; hardware in the loop work needs no flight.

## 9. The ask

Supervision; access for a few hours to a Cortex-M4F development board and a telemetry radio pair in a lab; and one representative flight controller profile (core, clock, free flash and RAM after the flight stack, link type) from a partner, which replaces the largest assumption in the fleet study. No purchase is required.
"""
    return doc, text


def variant(claim, org, doc, fit_lines):
    n = numbers(claim, doc)
    text = f"""# Proposal summary for {org}: post quantum ready command and update channels for drones and robots

Author: Huda Mueen. Two page summary of `docs/PROPOSAL_ROBOTICS.md`, generated by `scripts/build_paper.py`; every number is read from a result file.

{SEED_NOTE}

## Problem

Drones and robots authenticate commands and firmware on microcontroller flight computers over narrow links. The post quantum replacements are standardised, but their cost on such devices and links, and which devices must be replaced rather than updated, are not yet measured.

## Why this may be relevant (public facts only)

{fit_lines}

## What already exists

- {n['rows']} published rows with provenance, every new row read by two independent readers.
- A cycle model with a median held out error of {n['cm_med']} percent within one code base (modelled; signing misses by up to {n['cm_sign']} percent, and transfer to other code is untested), and board predictions registered in advance.
- A mission simulation: with a hybrid session, command availability on a telemetry radio stays at {n['m_b']}; a signature on every command lowers it to {n['m_c']} and adds about {n['m_c_lat']} ms per command (estimated).
- Firmware verification of a 1 MB image with LMS: about {n['boot_sw']} ms with a software hash, {n['boot_hw']} ms with hash hardware (estimated).
- Known gap: the link model is {n['d_factor']} times faster than a published 802.15.4 transfer time.

## Proposed next step

A short board session and a hardware in the loop study with a borrowed flight controller and telemetry radio, scored against predictions registered in this repository, followed by a reference design note for a session based command and update channel (`docs/REFERENCE_ARCHITECTURE.md`).

## The ask

Supervision or a contact for feedback; a few hours of lab access to a development board and a radio pair; one representative flight controller profile. No purchase is required.
"""
    return doc, text


def all_docs(claim):
    import csv
    from pathlib import Path
    root = Path(__file__).resolve().parents[1]
    facts = list(csv.DictReader(open(root / "data" / "context_entities.csv", encoding="utf-8")))

    def lines(org, ids):
        out = []
        for f in facts:
            if f["organisation"] == org and f["fact_id"] in ids:
                note = " The application window has closed." if f["fact_id"] == "EDGE-06" else ""
                out.append(f"- {f['paraphrase']}{note} ({f['fact_id']})")
        return "\n".join(out)

    docs = [robotics(claim)]
    docs.append(variant(claim, "TII and ATRC", "docs/PROPOSAL_ROBOTICS_ATRC.md",
                        lines("TII and ATRC", {"TII-02", "TII-04", "TII-05", "TII-06", "TII-07"})))
    docs.append(variant(claim, "EDGE Group", "docs/PROPOSAL_ROBOTICS_EDGE.md",
                        lines("EDGE Group", {"EDGE-01", "EDGE-02", "EDGE-05", "EDGE-06"})))
    docs.append(variant(claim, "ADEO", "docs/PROPOSAL_ROBOTICS_ADEO.md",
                        lines("ADEO", {"ADEO-01", "ADEO-02", "ADEO-03", "ADEO-04"})
                        + "\n\nADEO publishes little on technology under its own name; the items above that do not name ADEO are Abu Dhabi government statements, as `docs/CONTEXT_ENTITIES.md` notes."))
    return docs
