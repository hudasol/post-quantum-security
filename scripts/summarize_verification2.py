#!/usr/bin/env python3
"""Combine phase 2 verifier results into error rates (written to docs/VERIFICATION2.md and data/verify2/summary.csv)."""
import csv, glob, re, json
FIELDS = ['cycles','ram_bytes','stack_bytes','flash_or_code_bytes','energy_uj','key_or_sig_size_bytes','clock_mhz']
def load(batch):
    inp = {r['id']: r for r in csv.DictReader(open(f'data/verify2/{batch}.csv'))}
    res = {r['id']: r for r in csv.DictReader(open(f'data/verify2/{batch}_results.csv'))}
    return inp, res
out = []
tot = {}
for grp, batches in [('headline', ['H1','H2','H3','H4']), ('random', ['R1','R2','R3'])]:
    t = dict(rows=0, ok=0, error=0, unverifiable=0, wrong_value_rows=0, missing_only_rows=0, location_errors=0,
             populated=0, wrong_fields=0, missing_fields=0)
    for b in batches:
        inp, res = load(b)
        assert set(inp) == set(res), f'{b}: ids differ'
        for i, r in res.items():
            t['rows'] += 1
            st = r['status'].strip().upper()
            if st == 'OK': t['ok'] += 1
            elif st == 'ERROR': t['error'] += 1
            else: t['unverifiable'] += 1
            if st != 'UNVERIFIABLE':
                t['populated'] += sum(1 for f in FIELDS if inp[i][f].strip())
            if r['location_ok'].strip().lower() == 'no': t['location_errors'] += 1
            if st == 'ERROR':
                items = [x.strip() for x in re.split(r'[;,]\s*', r['wrong_fields']) if x.strip()]
                miss = [x for x in items if x.startswith('missing')]
                wrong = [x for x in items if not x.startswith('missing')]
                t['missing_fields'] += len(miss); t['wrong_fields'] += len(wrong)
                if wrong: t['wrong_value_rows'] += 1
                else: t['missing_only_rows'] += 1
    out.append((grp, t))
    for k, v in t.items(): tot[k] = tot.get(k, 0) + v
out.append(('combined', tot))
with open('data/verify2/summary.csv', 'w', newline='') as f:
    w = csv.writer(f); w.writerow(['set'] + list(tot))
    for g, t in out: w.writerow([g] + list(t.values()))
def pct(a, b): return f"{100*a/b:.1f}%" if b else 'n/a'
lines = ['# Verification, phase 2', '',
 'Independent verifiers reopened every source. Inputs, per row results and instructions are in `data/verify2/`. This file is generated by `scripts/summarize_verification2.py`.', '',
 '| Set | Rows | OK | ERROR | Unverifiable | Strict row error rate (ERROR / verifiable) | Wrong value rows | Missing only rows | Field wrong (of populated compared fields) | Location errors |',
 '|---|---|---|---|---|---|---|---|---|---|']
for g, t in out:
    ver = t['rows'] - t['unverifiable']
    lines.append(f"| {g} | {t['rows']} | {t['ok']} | {t['error']} | {t['unverifiable']} | {pct(t['error'], ver)} | {t['wrong_value_rows']} | {t['missing_only_rows']} | {t['wrong_fields']} of {t['populated']} ({pct(t['wrong_fields'], t['populated'])}) | {t['location_errors']} |")
lines += ['', 'Definitions. **Strict row error rate**: rows with at least one wrong or missing field, divided by rows that could be verified. **Wrong value rows**: a populated cell disagreed with the source. **Missing only rows**: the source reports a value the cell left empty (all of these were figures printed in rounded KB, now recorded verbatim in the warning column; see `data/corrections.csv`). Unverifiable rows (sources behind a block that the fetch tools could not read) are excluded from the rates and listed below.', '']
unv = []
for b in ['H1','H2','H3','H4','R1','R2','R3']:
    for r in csv.DictReader(open(f'data/verify2/{b}_results.csv')):
        if r['status'].strip().upper() == 'UNVERIFIABLE': unv.append(r['id'])
lines += ['Unverifiable rows: ' + ', '.join(unv), '']
open('docs/VERIFICATION2.md', 'w').write('\n'.join(lines))
print('\n'.join(lines))
