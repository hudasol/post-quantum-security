#!/usr/bin/env python3
"""Build docs/CONTEXT_ENTITIES.md from data/context_entities.csv. Author: Huda Mueen.

The CSV holds paraphrased public facts about three Abu Dhabi organisations, each with its URL, retrieval date and
page section. This script checks every row and writes the Markdown page; it adds no facts of its own."""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(ROOT, "data", "context_entities.csv")
MD_PATH = os.path.join(ROOT, "docs", "CONTEXT_ENTITIES.md")
COLUMNS = ["organisation", "fact_id", "paraphrase", "url", "retrieval_date", "page_section", "relevance"]
RETRIEVAL_DATE = "2026-10-20"
ORDER = ["TII and ATRC", "EDGE Group", "ADEO"]
TITLES = {
    "TII and ATRC": "Technology Innovation Institute (TII) and Advanced Technology Research Council (ATRC)",
    "EDGE Group": "EDGE Group",
    "ADEO": "Abu Dhabi Executive Office (ADEO) and related Abu Dhabi government statements",
}
# Pages that were requested during the retrieval pass but not returned. They are listed, not used.
NOT_RETRIEVED = [
    ("https://www.tii.ae/cryptography", "not retrieved; the same page was later retrieved at https://tii.ae/cryptography"),
    ("https://www.tii.ae/about-us", "not retrieved"),
    ("https://www.atrc.gov.ae/", "not retrieved"),
    ("https://www.atrc.gov.ae/about-atrc", "not retrieved (redirect target of https://atrc.ae/about-atrc)"),
    ("https://edgegroup.ae/share/print/news/765", "not retrieved (redirect target of an older domain)"),
    ("https://edgegroup.ae/share/pdf/news/998", "not retrieved (redirect target of an older domain)"),
    ("https://edgegroup.ae/share/print/news/820", "not retrieved (redirect target of an older domain)"),
    ("https://edgegroup.ae/share/pdf/news/756", "not retrieved (redirect target of an older domain)"),
]


def load(path=CSV_PATH):
    """Read the fact table as a list of dicts."""
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def validate(rows):
    """Return a list of problems: missing columns or values, wrong date, duplicate ids, non https URLs,
    unknown organisation, or a long paraphrase."""
    problems = []
    seen = set()
    for i, r in enumerate(rows, 1):
        if list(r.keys()) != COLUMNS:
            problems.append(f"row {i}: columns {list(r.keys())}")
            continue
        for c in COLUMNS:
            if not (r[c] or "").strip():
                problems.append(f"row {i}: empty {c}")
        if r["retrieval_date"] != RETRIEVAL_DATE:
            problems.append(f"row {i}: retrieval_date {r['retrieval_date']}")
        if not r["url"].startswith("https://"):
            problems.append(f"row {i}: url not https")
        if r["organisation"] not in ORDER:
            problems.append(f"row {i}: unknown organisation {r['organisation']}")
        if r["fact_id"] in seen:
            problems.append(f"row {i}: duplicate fact_id {r['fact_id']}")
        seen.add(r["fact_id"])
        if len(r["paraphrase"].split()) > 70:
            problems.append(f"row {i}: paraphrase longer than 70 words")
    return problems


def counts(rows):
    """Number of facts per organisation, in display order."""
    return {o: sum(1 for r in rows if r["organisation"] == o) for o in ORDER}


def cell(text):
    """Escape a value for a Markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def render(rows):
    """Return the Markdown page for the given rows."""
    n = counts(rows)
    out = [
        "# Context: public facts about three Abu Dhabi organisations",
        "",
        "Author: Huda Mueen. Generated by `scripts/build_context_entities.py` from `data/context_entities.csv`; "
        "do not edit by hand.",
        "",
        "Every fact below comes only from public web pages or official press releases of the organisations "
        "concerned, or from the Abu Dhabi Media Office, and is paraphrased in plain words. This repository is a "
        "student research seed. It has no relationship with, and no endorsement by, any of these organisations, "
        "and nothing here should be read as implying one. All pages were retrieved on "
        f"{RETRIEVAL_DATE}; pages change, so each fact holds only as of that date.",
        "",
        f"Facts recorded: {len(rows)} in total ("
        + ", ".join(f"{o}: {n[o]}" for o in ORDER) + ").",
        "",
        "Reading notes:",
        "",
        "- ADEO publishes little on technology under its own name. The ADEO section therefore also lists Abu Dhabi "
        "government statements on cyber security and digital strategy; each such row says when ADEO is not named.",
        "- Where a page does not name algorithms, licences or embedded targets, the row says so rather than "
        "filling the gap.",
        "- Dates of programmes and calls are those stated on the page; some windows have already closed.",
        "",
    ]
    for o in ORDER:
        out += [f"## {TITLES[o]}", "", "| Id | Fact (paraphrase) | Bearing on this work | Source and section |",
                "|---|---|---|---|"]
        for r in rows:
            if r["organisation"] != o:
                continue
            src = f"[{cell(r['url'])}]({r['url']}), {cell(r['page_section'])}, retrieved {r['retrieval_date']}"
            out.append(f"| {r['fact_id']} | {cell(r['paraphrase'])} | {cell(r['relevance'])} | {src} |")
        out.append("")
    out += ["## Pages requested but not retrieved", "",
            "These requests did not return content, so no fact was taken from them.", ""]
    out += [f"- {u}: {why}" for u, why in NOT_RETRIEVED]
    out.append("")
    return "\n".join(out)


def main():
    rows = load()
    problems = validate(rows)
    if problems:
        for p in problems:
            print("PROBLEM", p)
        return 1
    with open(MD_PATH, "w", encoding="utf-8") as f:
        f.write(render(rows))
    print(f"wrote {os.path.relpath(MD_PATH, ROOT)} with {len(rows)} facts: {counts(rows)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
