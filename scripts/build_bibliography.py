#!/usr/bin/env python3
"""Build data/bibliography.bib from the evidence table and the round 4 source notes.

Every source cited by a row of data/evidence.csv gets one entry (with the number of rows that
cite it). Every URL recorded in a committed round 4 source note or parameter file (data/raw/S12_*), the policy
timeline, the entity context or the reference profiles gets
an entry too, with the file that uses it, and so does every work of the round 6 related work file
(data/raw/S14_related_work.csv). Nothing is typed by hand; rerun after any change.
"""
import csv
import re
import subprocess
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "data" / "evidence.csv"
OUT = ROOT / "data" / "bibliography.bib"
URL_RE = re.compile(r"https?://[^\s|)\]>\"',;`]+")


def key_for(url):
    u = re.sub(r"^https?://(www\.)?", "", url.strip().lower()).rstrip("/.")
    host, _, path = u.partition("/")
    host = host.split(".")[-2] if host.count(".") >= 1 else host
    tail = re.sub(r"\.(pdf|html?|txt)$", "", path)
    tail = re.sub(r"[^a-z0-9]+", "_", tail).strip("_")
    return (host + "_" + tail)[:60].strip("_") or host


def clean(text):
    return (text or "").replace("{", "(").replace("}", ")").replace("\\", "/").replace("\n", " ").strip()


def collect():
    entries = OrderedDict()
    with open(EVIDENCE, newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            url = (row.get("source_url") or "").strip()
            if not url:
                continue
            e = entries.setdefault(url, {"title": clean(row.get("source_title")), "dates": set(),
                                         "rows": 0, "used_by": set()})
            e["rows"] += 1
            if row.get("retrieval_date"):
                e["dates"].add(row["retrieval_date"])
    tracked = subprocess.run(["git", "ls-files", "data/raw"], cwd=ROOT, capture_output=True, text=True).stdout.split()
    extra = ["data/policy_timeline.csv", "data/context_entities.csv", "data/reference_profiles.csv"]
    tracked_all = set(subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split("\n"))
    for path in sorted([ROOT / t for t in tracked if Path(t).name.startswith("S12")] + [ROOT / t for t in extra if t in tracked_all]):
        if path.suffix not in (".md", ".csv"):
            continue
        rel = path.relative_to(ROOT).as_posix()
        for url in URL_RE.findall(path.read_text(encoding="utf-8", errors="replace")):
            url = url.rstrip(".")
            e = entries.setdefault(url, {"title": "", "dates": set(), "rows": 0, "used_by": set()})
            e["used_by"].add(rel)
            e["dates"].add("2026-10-20")
    related = ROOT / "data" / "raw" / "S14_related_work.csv"
    if related.exists():  # round 6 related work (relwork/build_related_work.py); one entry per retrieved work
        with open(related, newline="", encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                url = (row.get("url") or "").strip()
                if not url or (row.get("read_via") or "").startswith("not retrieved"):
                    continue  # refused full texts are recorded in the CSV, not listed as retrieved sources
                e = entries.setdefault(url, {"title": clean(row.get("citation")), "dates": set(), "rows": 0, "used_by": set()})
                e["title"] = e["title"] or clean(row.get("citation"))
                e["used_by"].add("data/raw/S14_related_work.csv")
                if row.get("retrieval_date"):
                    e["dates"].add(row["retrieval_date"])
    return entries


def render(entries):
    seen, out = {}, ["% Generated by scripts/build_bibliography.py from data/evidence.csv and data/raw/S12_*; do not edit.", ""]
    for url, e in entries.items():
        k = key_for(url)
        n = seen.get(k, 0)
        seen[k] = n + 1
        if n:
            k = f"{k}_{n + 1}"
        note = f"Retrieved {', '.join(sorted(e['dates'])) or 'date not recorded'}."
        if e["rows"]:
            note += f" Cited by {e['rows']} rows of data/evidence.csv."
        if e["used_by"]:
            note += " Used by " + ", ".join(sorted(e["used_by"])) + "."
        out += [f"@misc{{{k},", f"  title = {{{e['title'] or url}}},", f"  howpublished = {{\\url{{{url}}}}},",
                f"  note = {{{note}}}", "}", ""]
    return "\n".join(out)


def keys(text):
    return set(re.findall(r"^@misc\{([^,]+),", text, re.M))


def main():
    text = render(collect())
    if "--check" in sys.argv:
        old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if old != text:
            sys.exit("data/bibliography.bib is stale: run python3 scripts/build_bibliography.py")
        print(f"bibliography current: {len(keys(text))} entries")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(keys(text))} entries")


if __name__ == "__main__":
    main()
