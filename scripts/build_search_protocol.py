#!/usr/bin/env python3
"""Write docs/SEARCH_PROTOCOL.md from the search logs of rounds 4, 5 and 6.

Round 4: data/raw/S12_search_log*.csv; the protocol part is fixed text below.
Round 5 (stream S13): the protocol is data (data/raw/S13_protocol.csv), the query log is
data/raw/S13_search_log.csv and the flow counts are data/raw/S13_prisma.csv (written by
scripts/build_s13_prisma.py, which this script runs first). Flow tables, the flow diagram and
the query lists are computed from these files, so they cannot drift from what was searched.
Round 6 (stream S14, dblp): data/raw/S14_dblp_log.csv, S14_dblp_records.csv and S14_screening.csv, written by
relwork/build_s14_dblp.py, which this script runs first.
"""
import csv
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

PROTOCOL = """# Search protocol and flow, rounds 4, 5 and 6

Author: Huda Mueen. Generated by `scripts/build_search_protocol.py` from the search logs; do not edit by hand.

## Round 4 protocol

Question: what published measurements exist of the cost of post quantum and classical public key cryptography, and of the protocols that carry it, on microcontroller class devices and constrained links, and of the hardware and traffic of drone and robot systems.

Sources searched: IACR ePrint and TCHES, arXiv, IEEE Xplore and ACM abstract pages where retrievable, standards bodies (NIST, IETF), project repositories with benchmark tables, vendor documentation and application notes, and the reference lists of every supplied paper (citation chasing).

Tools: the web search and fetch tools of the working environment only. Pages that refused or timed out were not retrieved by other means; they are listed for the author.

Inclusion: a measured or specified value with its conditions stated in a table or an explicit sentence, on a microcontroller class core, an open MCU class core design, a constrained link, or a drone or robot platform; read in full text by the extraction pass.

Exclusion: values only in figures without numbers, summaries that could not be checked against the original text, host only measurements (kept elsewhere), duplicates of rows already in `data/evidence.csv`, and sources that could not be retrieved.

Every included value was then read by two independent readers (`docs/VERIFICATION5.md`).
"""


def main():
    tracked = subprocess.run(["git", "ls-files", "data/raw"], cwd=ROOT, capture_output=True, text=True).stdout.split()
    logs = [ROOT / t for t in tracked if Path(t).name.startswith("S12_search_log")]
    rows = []
    for p in sorted(logs):
        with open(p, newline="", encoding="utf-8") as fh:
            for r in csv.DictReader(fh):
                r["_log"] = p.name
                rows.append(r)

    def total(col):
        s = 0
        for r in rows:
            try:
                s += int(float((r.get(col) or "0").strip() or 0))
            except ValueError:
                pass
        return s

    lines = [PROTOCOL, "## Round 4 flow", "",
             "| stage | records |", "|---|---|",
             f"| searches run | {len(rows)} |",
             f"| records returned | {total('records_returned')} |",
             f"| records screened | {total('records_screened')} |",
             f"| read in full | {total('read_in_full')} |",
             f"| included (as logged per search: evidence rows or facts taken, not sources) | {total('included')} |",
             "", "Counts are summed over searches; a source found by several searches is counted once per search. The round 4 logs "
             "recorded in the included column the number of rows or facts taken from the search, so it can exceed the number read in full.", "",
             "## Round 4 searches", "", "| log | stream | date | tool | query | returned | screened | read in full | included | exclusions |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        cells = [r["_log"], r.get("stream", ""), r.get("date", ""), r.get("tool", ""), r.get("query", ""),
                 r.get("records_returned", ""), r.get("records_screened", ""), r.get("read_in_full", ""),
                 r.get("included", ""), r.get("excluded_reason_summary", "")]
        lines.append("| " + " | ".join(str(c).replace("|", "/").replace("\n", " ") for c in cells) + " |")
    lines += round5()
    lines += round6()
    (ROOT / "docs" / "SEARCH_PROTOCOL.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} round 4 searches from {len(logs)} logs; round 5 and round 6 sections written")


def _csv(name):
    with open(ROOT / "data" / "raw" / name, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def cell(x):
    return str(x).replace("|", "/").replace("\n", " ")


def first_commit(path):
    """Hash of the commit that added the file, or '' if git has no record."""
    r = subprocess.run(["git", "log", "--diff-filter=A", "--format=%h", "--", path], cwd=ROOT, capture_output=True, text=True)
    lines = r.stdout.split()
    return lines[-1] if lines else ""


def timing_note():
    names = ["data/raw/S13_protocol.csv", "data/raw/S13_search_log.csv", "data/raw/S13_screening.csv"]
    c = [first_commit(n) for n in names]
    if c[0] and c[0] == c[1] == c[2]:
        return ("The row 'written' states that the protocol was written before the first round 5 query was screened. The git history does "
                f"not evidence this timing: the protocol was first committed in the same commit ({c[0]}) as the search log and the screening "
                "file, and no hash of it is recorded in the repository. Rows named deviation were added on the date they state, after "
                "screening and after review, and are disclosed as deviations from the protocol as first written.")
    return ("The row 'written' states when the protocol was written; rows named deviation were added later on the date they state "
            "and are disclosed as deviations.")


def demoted_section():
    p = ROOT / "data" / "raw" / "S13_demoted.csv"
    if not p.exists():
        return []
    dem = _csv("S13_demoted.csv")
    staged = {r["id"]: r for r in _csv("S13_staged.csv")}
    groups = {}
    for d in dem:
        k = (staged[d["id"]]["source_title"][:90], d["rule"], d["reason"], d["date"])
        groups.setdefault(k, []).append(d["id"])
    out = ["", "## Round 5 rows demoted after review", "",
           "Rows that were double read but break a written rule are kept in staging and out of the evidence table "
           "(`data/raw/S13_demoted.csv`, applied by `scripts/promote_s13.py`).", "",
           "| source | rows | rule | reason | date |", "|---|---|---|---|---|"]
    for (src, rule, why, date), ids in groups.items():
        out.append(f"| {cell(src)} | {len(ids)} ({ids[0]} to {ids[-1]}) | {cell(rule)} | {cell(why)} | {date} |")
    return out


def round5():
    """Round 5 section: protocol from S13_protocol.csv, flow from S13_prisma.csv, queries from S13_search_log.csv."""
    if not (ROOT / "data" / "raw" / "S13_protocol.csv").exists():
        return []
    subprocess.run([sys.executable, str(ROOT / "scripts" / "build_s13_prisma.py")], check=True, capture_output=True)
    proto = _csv("S13_protocol.csv")
    flow = _csv("S13_prisma.csv")
    log = _csv("S13_search_log.csv")
    scr = _csv("S13_screening.csv")
    out = ["", "## Round 5 protocol (stream S13)", "",
           "Read from `data/raw/S13_protocol.csv`. " + timing_note(), "",
           "| item | rule |", "|---|---|"]
    out += [f"| {cell(p['key'].replace('_', ' '))} | {cell(p['value'])} |" for p in proto]
    main = [f for f in flow if not f["stage"].startswith("excluded: ")]
    reasons = [f for f in flow if f["stage"].startswith("excluded: ")]
    out += ["", "## Round 5 flow", "", "Counts from `data/raw/S13_prisma.csv`.", "",
            "| stage | count | how counted |", "|---|---|---|"]
    out += [f"| {cell(f['stage'])} | {f['count']} | {cell(f['how_counted'])} |" for f in main]
    out += ["", "Exclusions after an abstract or full text was assessed, by reason:", "",
            "| reason | records |", "|---|---|"]
    out += [f"| {cell(f['stage'][len('excluded: '):])} | {f['count']} |" for f in reasons]
    c = {f["stage"]: f["count"] for f in main}
    box = [("identified", "identified"), ("screened on title and snippet", "screened"),
           ("eligible (abstract or full text assessed)", "eligible"), ("included sources", "included sources"),
           ("staged rows", "staged rows"), ("rows confirmed by two readers and promoted", "double read and promoted")]
    out += ["", "Flow diagram (text form):", "", "```"]
    for i, (k, name) in enumerate(box):
        out.append(f"[ {name}: {c.get(k, '0')} ]")
        if i < len(box) - 1:
            out.append("        |")
            out.append("        v")
    out += ["```", "", "## Round 5 records assessed beyond the title", "",
            "| record | found by | stage | decision | reason | rows staged |", "|---|---|---|---|---|---|"]
    out += [f"| {cell(r['record'])} | {r['found_by']} | {r['stage_reached']} | {r['decision']} | {cell(r['exclusion_reason'])} | {r['rows_staged']} |" for r in scr]
    out += demoted_section()
    out += ["", "## Round 5 queries", "",
            "| id | date | tool | database | query | returned | screened | read in full | included | excluded | exclusion reasons |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in log:
        out.append("| " + " | ".join(cell(r[k]) for k in ("query_id", "date", "tool", "database", "query", "records_returned",
                                                       "records_screened", "read_in_full", "included", "excluded",
                                                       "excluded_reason_summary")) + " |")
    out += ["", "A record found by several queries is counted once per query in the query table and once in the records table. "
            "The included count of each query equals the number of included records whose found by entry names it; the backward "
            "snowballing row counts none because the sources it read in full had already been found by searches.", ""]
    return out


def round6():
    """Round 6 section (stream S14, question Q13): the dblp search, from the files written by relwork/build_s14_dblp.py."""
    if not (ROOT / "data" / "raw" / "S14_dblp_search_raw.csv").exists():
        return []
    subprocess.run([sys.executable, str(ROOT / "relwork" / "build_s14_dblp.py")], check=True, capture_output=True)
    log = _csv("S14_dblp_log.csv")
    recs = _csv("S14_dblp_records.csv")
    scr = _csv("S14_screening.csv")
    run = [r for r in log if r["status"] == "run"]
    refused = [r for r in log if r["status"] == "refused"]
    passing = [r for r in recs if r["title_screen"] == "pass"]
    out = ["", "## Round 6 protocol (stream S14, dblp)", "",
           "Question: does an index of IEEE and ACM venues add sources to the round 5 search? The round 5 query themes "
           "(post quantum, ML-KEM, ML-DSA, Kyber, Dilithium, Falcon, SPHINCS, LMS and XMSS, combined with microcontroller, "
           "Cortex-M, RISC-V, embedded, IoT, drone, UAV, MAVLink, robot, ROS, secure boot and firmware update) were combined into "
           "the queries listed below and run against dblp; not every pairing of terms was run. The records were screened on title with the round 5 inclusion and exclusion rules "
           "(`data/raw/S13_protocol.csv`). Records passing the title screen are listed for later full text reading; no evidence "
           "row is staged from them in this round.", "",
           "Deviation, disclosed: the dblp search API, the dblp search page and the dblp record pages were refused by the fetch "
           "tool (rows " + ", ".join(r["query_id"] for r in refused) + " of `data/raw/S14_dblp_log.csv`), and were not worked "
           "around. The queries were therefore run with the web search tool restricted to the dblp.org domain. Each query "
           "returns at most ten results of that search, not the dblp hit count, so the counts below measure what the search tool "
           "surfaced from dblp, not the index. Venue names, years and DOIs could not be read from the records; the venue stream "
           "and a year hint are taken from the dblp key and marked as such.", "",
           "Seen before: a record counts as seen in the round 5 screening if its normalised title or its arXiv id occurs in "
           "`data/raw/S13_screening.csv`, `S13_arxiv_hits.csv`, `S13_search_log.csv` or `S13_staged.csv`, and as known to the "
           "repository if it occurs in `data/bibliography.bib`, `data/evidence.csv` or a round 4 or 5 source note. DOIs were not "
           "available for matching.", "",
           "## Round 6 flow", "",
           "Counts from `data/raw/S14_dblp_log.csv`, `S14_dblp_records.csv` and `S14_screening.csv`; "
           "`relwork/check_s14_counts.py` recomputes them.", "",
           "| stage | count |", "|---|---|",
           f"| queries run | {len(run)} |",
           f"| fetches refused | {len(refused)} |",
           f"| results returned (summed over queries) | {sum(int(r['results_returned']) for r in run)} |",
           f"| dblp record pages among them (summed over queries) | {sum(int(r['record_pages']) for r in run)} |",
           f"| distinct records | {len(recs)} |",
           f"| records passing title screening | {len(passing)} |",
           f"| of these, not seen in the round 5 screening | {sum(r['seen_round5_screening'] == 'no' for r in passing)} |",
           f"| of these, also not known to the repository (new) | {sum(r['new_record'] == 'yes' for r in scr)} |",
           "", "## Round 6 records passing title screening", "",
           "| record | found by | rule | reason | round 5 gap by title | seen in round 5 | known to repository | new |",
           "|---|---|---|---|---|---|---|---|"]
    out += [f"| {cell(r['title'])} ({cell(r['dblp_key'])}) | {r['found_by']} | {cell(r['rule'])} | {cell(r['reason'])} | "
            f"{cell(r['round5_gap_by_title'])} | {r['seen_round5_screening']} | {r['in_repository_sources']} | {r['new_record']} |" for r in scr]
    out += ["", "## Round 6 queries", "",
            "| id | date | tool | query | returned | record pages | person pages | venue pages | first seen | passing | status |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    out += ["| " + " | ".join(cell(r[k]) for k in ("query_id", "date", "tool", "query", "results_returned", "record_pages",
                                                   "person_pages", "venue_or_volume_pages", "records_first_seen",
                                                   "records_passing_title_screen", "status")) + " |" for r in log]
    out += ["", "A record found by several queries is counted once per query in the query table and once in the record list.", ""]
    return out


if __name__ == "__main__":
    main()
